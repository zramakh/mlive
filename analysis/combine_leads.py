#!/usr/bin/env python3
"""Do the observed leads work better combined? Every pair and triple of the ranked leads of the same game, merged by
adding each lead's rank of every number (lowest total first), against the leads alone.

Per lead or combination: drawn numbers in the top ticket (8 Magnum Life, 6 Toto) against exact chance over the whole
history (from draw 100) and over the forward years of the fair test (Magnum Life / Star from 2022, Power / Supreme
from 2017), and the 10-set (10-ticket) prize return on the forward years. Luck check: the same combinations with
the parameter leads' values rolled against the draws (5 shifted calendars; the lunar rule shifted 6-72 days).

python3 analysis/combine_leads.py  -> analysis/COMBINE_LEADS.md
"""

import itertools
import math
import os
import sys

import numpy as np

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import watch_rank as wr  # noqa: E402
import seasonal7 as s7  # noqa: E402

ws, ls, common, xa = wr.ws, wr.ls, wr.common, wr.xa
A = wr.A
LEADS = {
    "ml8": [("mars_rashi × month", "cold"), ("rahu_nakshatra × aspect_moon_venus", "cold/hot100")],
    "toto50": [("lunar_date", "hot/cold100@7"), ("lagna_rashi × lunar_month", "pos"), ("lunar_date", "hot@7"),
               ("lunar_date", "pos@7")],
    "toto55": [("karana × aspect_mercury_jupiter", "hot/cold100"), ("year_stem × lagna_navamsa_lord", "cold"),
               ("masa × adhika_masa", "hot+100")],
    "toto58": [("day_of_month × aspect_venus_mars", "cold/hot100"), ("plum_trigrams × saturn_navamsa", "hot/cold100")],
}
FWD = {"ml8": "2022-01-01", "toto50": "2022-01-01", "toto55": "2017-01-01", "toto58": "2017-01-01"}
NSH = 5


def ranks(key, lead, pat, sh):
    """Rank position of every number for every draw (0 = best)."""
    W = ls.W
    if lead == "lunar_date":
        if sh:
            p, _, w = pat.partition("@")
            old = s7.window_sums

            def shifted(X, yi, day, period, Wd, off, ny):
                return old(X, yi, day, period, Wd, off + 12 * sh, ny)
            s7.window_sums = shifted
            try:
                order = ws.lunar_ranking(pat)
            finally:
                s7.window_sums = old
        else:
            order = ws.lunar_ranking(pat)
    else:
        names = common.ALL_PARAMS + xa.extra_params()
        codes = W["codes"]
        if sh:
            W["codes"] = np.roll(codes, 151 * sh + 160, axis=0)
        try:
            order = ws.ranking([names.index(x) for x in lead.split(" × ")], pat)
        finally:
            W["codes"] = codes
    R = np.empty_like(order)
    np.put_along_axis(R, order, np.arange(order.shape[1])[None, :], 1)
    return R


def evaluate(key, R, t0):
    W = ls.W
    k, n, H = W["k"], W["n"], W["H"]
    order = np.argsort(R + W["tie"], 1)
    e, v = k * k / n, k * (k / n) * (1 - k / n) * (n - k) / (n - 1)
    hits = np.take_along_axis(H, order[:, :k], 1).sum(1)
    out = {}
    for nm, lo in (("all", 100), ("fwd", t0)):
        h, nd = hits[lo:].sum(), len(hits) - lo
        out[nm] = (h / (nd * e), (h - nd * e) / math.sqrt(nd * v))
    fmt = "10 tickets" if key == "ml8" else "10 sets"
    pay, _, cost = wr.score(key, order, fmt, t0)
    out["ret"] = pay[t0:].sum() / (cost * (len(pay) - t0))
    return out


def main():
    md = ["# Combining the observed leads", "", "Generated by `analysis/combine_leads.py`. Combination = the leads' ranks of each number "
          "added (lowest total first). *Ratio (z)* = drawn numbers in the top ticket against chance; *forward* = the fair-test "
          "years; *10-set return* = prizes per RM1 on the forward years. Shifted = the same combination on 5 shifted "
          "calendars (median z).", ""]
    for key, leads in LEADS.items():
        ls.init(key)
        dates = ls.W["g"]["dates"]
        t0 = next(i for i, x in enumerate(dates) if x >= FWD[key])
        Rs = {sh: [ranks(key, l, p, sh) for l, p in leads] for sh in range(NSH + 1)}
        lab = [f"{l} ({p})" for l, p in leads]
        md += [f"## {wr.LABEL[key]} (forward from {FWD[key]})", "",
               "| Leads | Whole history: ratio (z) | Forward: ratio (z) | Forward, shifted (median z) | Forward 10-set return |", "|---|---|---|---|---|"]
        combos = [c for r in range(1, min(3, len(leads)) + 1) for c in itertools.combinations(range(len(leads)), r)]
        rows = []
        for c in combos:
            if key == "toto50" and sum(leads[i][0] == "lunar_date" for i in c) > 1:
                continue                                            # two versions of the same rule
            r0 = evaluate(key, sum(Rs[0][i] for i in c), t0)
            zs = [evaluate(key, sum(Rs[sh][i] for i in c), t0)["fwd"][1] for sh in range(1, NSH + 1)]
            rows.append((c, r0, float(np.median(zs))))
        rows.sort(key=lambda r: -r[1]["fwd"][1])
        for c, r0, zs in rows:
            md.append(f"| {' + '.join(lab[i] for i in c)} | ×{r0['all'][0]:.3f} ({r0['all'][1]:+.1f}) | ×{r0['fwd'][0]:.3f} ({r0['fwd'][1]:+.1f}) | "
                      f"{zs:+.1f} | {r0['ret']:.2f} |")
        md.append("")
        print(wr.LABEL[key], "done", flush=True)
    open(os.path.join(A, "COMBINE_LEADS.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
