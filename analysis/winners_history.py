#!/usr/bin/env python3
"""How did the biggest winners of a draw do before it?

Takes the "Biggest payouts today" leads of LEADS7_TODAY_<date>.md (lead_today.py) and looks each one up in
lead_full.py's arrays (draws up to the day before): its profit and rank on the earlier draws, its winning draws
and high hits there (and on the 20 shifted calendars), and every one of the last 10 draws before the date.

python3 analysis/winners_history.py 2026-10-18  -> analysis/WINNERS_HISTORY_<date>.md
"""

import itertools
import os
import re
import sys

import numpy as np

DATE = sys.argv[1]
WIN = sys.argv[sys.argv.index("--window") + 1] if "--window" in sys.argv else "all"
FAM = ["--family", sys.argv[sys.argv.index("--family") + 1]] if "--family" in sys.argv else []
sys.argv = [sys.argv[0], "--shifts", "1", "--window", WIN] + FAM + ["--until", DATE]      # the data cut at DATE: it is the last row
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lead_full as lf  # noqa: E402

common, xa = lf.common, lf.xa
A = os.path.join(common.ROOT, "analysis")
LABELS = {"Magnum Life 8/36": "ml8", "STAR TOTO 6/50": "toto50", "POWER TOTO 6/55": "toto55", "SUPREME TOTO 6/58": "toto58"}


def winners():
    """{game key: [(lead, pattern, format, combination, payout)]} from the LEADS7_TODAY file."""
    out, key, on = {}, None, False
    for ln in open(os.path.join(A, f"LEADS7{lf.TAG.upper()}_TODAY_{DATE}.md")):
        if ln.startswith("## "):
            key = LABELS[ln[3:].split(":")[0]]
            on = False
        elif ln.startswith("Biggest payouts"):
            on = True
        elif ln.startswith("Leads singled"):
            on = False
        elif on and ln.startswith("| ") and not ln.startswith("| Lead") and not ln.startswith("|---"):
            c = [x.strip() for x in ln.strip().strip("|").split("|")]
            out.setdefault(key, []).append((c[0], c[1].replace(" (new)", ""), c[2], c[3], float(c[4].replace(",", ""))))
    return out


def main():
    names = common.ALL_PARAMS + xa.extra_params()
    sets = lf.lead_sets(names)
    pos = {}
    for si, s in enumerate(sets):
        nm = " × ".join(names[j] for j in s) if s else "all draws (no astrology)"
        for pi, p in enumerate(lf.PATS):
            pos[(nm, p)] = si * lf.NP + pi
    W = winners()
    md = [f"# The biggest winners of {DATE}: how they did before", "",
          "Generated by `analysis/winners_history.py` from `lead_full.py` (history up to the day before, 7 patterns). "
          "*Earlier* = the draws from 25% of the history to the 10 draws before the date; *rank* = by earlier profit in "
          "that format (of 45,892 leads); *return* = payout ÷ stake there (random entries: Magnum Life 55%, Star 35%, "
          "Power / Supreme 20%). *High hits* = 7+ numbers (Magnum Life) or 5+ (Toto) in one combination; *shifted* = the "
          "same lead on 20 calendars out of line with the draws. *Last 10* = each of the 10 draws before the date: best "
          "combination, and the draw's profit.", ""]
    for key, rows in W.items():
        z = np.load(os.path.join(A, "profit_arrays", f"leads7{lf.TAG}_{key}.npz"))
        PRE, ST, HO, HC = z["PRE"], z["ST"], z["HO"], z["HC"]
        dates = [str(x) for x in z["dates"]]
        lf.setup(key)
        fm, cost, k = lf.G["fmt"], lf.G["cost"], lf.G["k"]
        g = common.load_game(key)
        d = len(g["dates"]) - 1                                      # draws before DATE
        R = d - 10
        n_pre = R - int(0.25 * R)
        label = [l_ for l_, v in LABELS.items() if v == key][0]
        md += [f"## {label}", "",
               "| Lead | Pattern | Format | Today | Earlier: rank / return / winning draws | Earlier high hits (shifted mean) | Last 10: profit | Last 10, best combination per draw |",
               "|---|---|---|---|---|---|---|---|"]
        rank = {}
        for fi in range(4):
            r = np.empty(len(PRE), int)
            r[np.argsort(-PRE[:, 0, fi], kind="stable")] = np.arange(1, len(PRE) + 1)
            rank[fi] = r
        for lead, pat, f, comb, pay in rows:
            i, fi = pos[(lead, pat)], fm.index(f)
            ret = 1 + PRE[i, 0, fi] / (cost[f] * n_pre)
            wins = int(ST[i, 0, fi, 0])
            hi, hi_sh = int(ST[i, 0, fi, 1]), float(ST[i, 1:, fi, 1].mean())
            l10 = float(HO[i, 0, fi].sum())
            per = " ".join(lf.tier(int(c), k) for c in HC[i, 0, fi])
            md.append(f"| {lead} | {pat}{' (new)' if pat in lf.NEW else ''} | {f} | {comb}, RM{pay:,.0f} | {rank[fi][i]:,} / "
                      f"{100 * ret:.0f}% / {wins} of {n_pre} ({100 * wins / n_pre:.1f}%) | {hi} ({hi_sh:.1f}) | {l10:+,.0f} | {per} |")
        md += ["", f"Last 10 draws: {', '.join(x[5:] for x in dates)}.", ""]
    out = os.path.join(A, f"WINNERS_HISTORY{lf.TAG.upper()}_{DATE}.md")
    with open(out, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
