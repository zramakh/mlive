#!/usr/bin/env python3
"""Consensus tickets (5 ordinary tickets per game) from predict_<date>.csv, scored when the draw is in data/.

Each watchlist lead (counted once) scores its 12 top numbers (12 points down to 1), weighted by its WATCH_RANK.md
position; ticket = the top 6 (Magnum Life) / 4 (Toto) numbers plus two of the next ten in turn.

python3 analysis/consensus.py 2026-10-14 2026-10-17 2026-10-18 2026-10-21
"""
import collections
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import profit_rank as pr  # noqa: E402
import toto_profit as tp  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
GAMES = {"Magnum Life": ("ml8", 8), "Star Toto": ("toto50", 6), "Power Toto": ("toto55", 6), "Supreme Toto": ("toto58", 6)}


def tickets(date):
    rows = list(csv.DictReader(open(os.path.join(A, f"predict_{date}.csv"))))
    n = len(rows)
    out = {}
    for g, (key, k) in GAMES.items():
        seen, sc = set(), collections.Counter()
        for r in rows:
            if r["game"] != g or (r["lead"], r["pat"]) in seen:
                continue
            seen.add((r["lead"], r["pat"]))
            w = 1 - (int(r["rank"]) - 1) / n
            for i, x in enumerate(r["top"].split()):
                sc[int(x)] += w * (12 - i) / 12
        order = [x for x, _ in sc.most_common()]
        core, rest = order[:k - 2], order[k - 2:k + 8]
        out[g] = [sorted(core + rest[2 * i:2 * i + 2]) for i in range(5)]
    return out


def result(key, date):
    for r in csv.DictReader(open(os.path.join(common.DATA, common.GAMES[key][0]))):
        if r["draw_date"] == date:
            main = {int(r[f"n{i}"]) for i in range(1, 9) if r.get(f"n{i}")}
            bon = {int(r[c]) for c in ("bonus", "bonus1", "bonus2") if r.get(c)}
            return main, bon
    return None


def main():
    md = ["# Consensus tickets scored", "", "Generated by `analysis/consensus.py`; 5 ordinary tickets per game per draw.", ""]
    for date in [a for a in sys.argv[1:] if a[:2] == "20"]:
        md += [f"## {date}", "", "| Game | Ticket | Matched | Prize (RM) |", "|---|---|---|---|"]
        for g, T in tickets(date).items():
            key, k = GAMES[g]
            res = result(key, date)
            table = pr.pay_table(8) if key == "ml8" else tp.pay_table(key)
            for t in T:
                if res:
                    m, b = len(res[0] & set(t)), len(res[1] & set(t))
                    pay = table[m, min(b, table.shape[1] - 1)]
                    hit = " ".join(f"**{x:02d}**" if x in res[0] else (f"*{x:02d}*" if x in res[1] else f"{x:02d}") for x in t)
                    md.append(f"| {g} | {hit} | {m}" + (f"+{b}b" if b else "") + f" | {pay:,.0f} |")
                else:
                    md.append(f"| {g} | {' '.join(f'{x:02d}' for x in t)} | | |")
        md.append("")
    open(os.path.join(A, "CONSENSUS_SCORED.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
