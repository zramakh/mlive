#!/usr/bin/env python3
"""Star Toto same-lunar-date rule: every pattern × day window × ticket plan, over several periods, and a fair choice.

Rule: the cell of a draw = earlier-year draws within ±W days of the same Chinese lunar date (months as 30 days); the
7 patterns rank the numbers from it (seasonal7.py). Ticket plans (positions in that ranking, best first):
  top6 (1 ticket), 5+2 (2), 5+3 (3), 4+4 (6), wheel7 (7, System 7), swap10 (10 sets), 3+6 (20), wheel8 (28, System 8)
Official Star prizes (RM1 a ticket). Per configuration: return per RM1 and share of draws with a prize over the last
10 / 50 / 100 / 200 / 500 draws and the whole history (from draw 100), and per year.

Fair choice (walk-forward): before each year from 2020, the configuration with the best return on the earlier years
only is played that year; also the best (pattern, window) for each plan separately. Luck check: the whole procedure
with the window centred on 20 other dates (18 days apart).

python3 analysis/lunar_opt.py  -> analysis/LUNAR_OPT.md, lunar_opt.json
"""

import csv
import datetime as dt
import itertools
import json
import os
import sys
from multiprocessing import Pool

import numpy as np

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ephemeris as eph  # noqa: E402
import lead_search10 as ls  # noqa: E402
import seasonal7 as s7  # noqa: E402
import toto_profit as tp  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
PATS = s7.PATS
WS = [3, 5, 7, 10, 14]


def plan(c, q):
    return [list(range(c)) + [c + i for i in comb] for comb in itertools.combinations(range(q), 6 - c)]


PLANS = {"top6": [list(range(6))], "5+2": plan(5, 2), "5+3": plan(5, 3), "4+4": plan(4, 4),
         "wheel7": [list(s) for s in itertools.combinations(range(7), 6)], "swap10": ls.swap_patterns(6),
         "3+6": plan(3, 6), "wheel8": [list(s) for s in itertools.combinations(range(8), 6)]}
OFFSETS = [0] + list(range(18, 360, 18))

ls.init("toto50")
Wd = ls.W
k, n, d = Wd["k"], Wd["n"], Wd["d"]
DATES = Wd["g"]["dates"]
days = [dt.date.fromisoformat(x) for x in DATES]
YEARS = np.array([x.year for x in days])
yi = YEARS - YEARS.min()
ny = yi.max() + 1
lunar = np.array([(eph.lunar_date(x)[0] - 1) * 30 + eph.lunar_date(x)[1] - 1 for x in days])
BON = np.array([int(r["bonus"]) for r in csv.DictReader(open(os.path.join(common.DATA, "star_toto_6_50.csv")))]) - 1
T = tp.pay_table("toto50")
LO = 100


def payouts(off):
    """[pattern][W][plan] -> per-draw payout (d,) for one centre offset."""
    out = np.zeros((len(PATS), len(WS), len(PLANS), d), np.float32)
    Bm = np.zeros((d, n))
    Bm[np.arange(d), BON] = 1
    for wi, W in enumerate(WS):
        cnt = s7.window_sums(Wd["H"], yi, lunar, 360, W, off, ny)
        dp = s7.window_sums(np.ones((d, 1)), yi, lunar, 360, W, off, ny)
        Pw = s7.window_sums(Wd["P"], yi, lunar, 360, W, off, ny)
        e = dp * k / n
        zc = (cnt - e) / np.sqrt(e * (1 - k / n) + 1e-6)
        S = {"hot": cnt - e, "cold": e - cnt, "pos": ((Pw + ls.SMOOTH * Wd["pglob"]) / (dp[:, :, None] + ls.SMOOTH)).sum(1),
             "hot+100": zc + Wd["hot100"], "cold+100": -zc - Wd["hot100"], "hot/cold100": zc - Wd["hot100"],
             "cold/hot100": -zc + Wd["hot100"]}
        for p, pat in enumerate(PATS):
            rk = np.argsort(-(S[pat] + Wd["tie"]), axis=1)[:, :10]
            Hr = np.take_along_axis(Wd["H"], rk, 1)
            Br = np.take_along_axis(Bm, rk, 1)
            for j, P in enumerate(PLANS.values()):
                pay = np.zeros(d)
                for s in P:
                    pay += T[Hr[:, s].sum(1).astype(int), Br[:, s].sum(1).astype(int)]
                out[p, wi, j] = pay
            out[p, wi, :, dp[:, 0] < 3] = np.nan
    return off, out


def main():
    with Pool(4) as pool:
        R = dict(pool.map(payouts, OFFSETS))
    cost = np.array([len(P) for P in PLANS.values()], float)
    names = list(PLANS)
    idx = np.arange(LO, d)
    md = ["# Star Toto lunar-date rule: patterns × windows × ticket plans", "", "Generated by `analysis/lunar_opt.py` (see the script). "
          "Return = prizes per RM1 staked (random tickets: about 0.35 long-run, with rare big prizes; without them about 0.2).", ""]
    # 1. periods, real date: every configuration's return; show the best 15 by whole-history return and a few fixed ones
    real = R[0]
    periods = {"last 10": 10, "last 50": 50, "last 100": 100, "last 200": 200, "last 500": 500, "all": d - LO}
    rows = []
    for p, wi, j in itertools.product(range(len(PATS)), range(len(WS)), range(len(PLANS))):
        x = real[p, wi, j]
        r = {nm: float(np.nansum(x[-m:]) / (cost[j] * np.sum(~np.isnan(x[-m:])))) for nm, m in periods.items()}
        w = {nm: float(np.nanmean(x[-m:] > 0)) for nm, m in periods.items()}
        rows.append((PATS[p], WS[wi], names[j], r, w))
    rows.sort(key=lambda r: -r[3]["all"])
    md += ["## Best configurations by whole-history return (real date)", "",
           "| Pattern | ± days | Plan (tickets) | " + " | ".join(periods) + " | Draws with a prize (all) |", "|---|---|---|" + "---|" * len(periods) + "---|"]
    for pat, W, pl, r, w in rows[:20]:
        md.append(f"| {pat} | {W} | {pl} ({len(PLANS[pl])}) | " + " | ".join(f"{r[x]:.2f}" for x in periods) + f" | {w['all']:.1%} |")
    # 2. per plan: the median over patterns and windows, real vs other dates
    md += ["", "## Each ticket plan, all patterns and windows together (median return, whole history)", "",
           "| Plan | Tickets | Real date | Other dates (median) | Share of draws with a prize: real | other dates |", "|---|---|---|---|---|---|"]
    for j, nm in enumerate(names):
        rr = np.nanmedian([np.nansum(R[0][p, wi, j, LO:]) / (cost[j] * np.sum(~np.isnan(R[0][p, wi, j, LO:]))) for p in range(len(PATS)) for wi in range(len(WS))])
        ro = np.median([np.nanmedian([np.nansum(R[o][p, wi, j, LO:]) / (cost[j] * np.sum(~np.isnan(R[o][p, wi, j, LO:]))) for p in range(len(PATS)) for wi in range(len(WS))]) for o in OFFSETS[1:]])
        wr = np.nanmedian([np.nanmean(R[0][p, wi, j, LO:] > 0) for p in range(len(PATS)) for wi in range(len(WS))])
        wo = np.median([np.nanmedian([np.nanmean(R[o][p, wi, j, LO:] > 0) for p in range(len(PATS)) for wi in range(len(WS))]) for o in OFFSETS[1:]])
        md.append(f"| {nm} | {len(PLANS[nm])} | {rr:.2f} | {ro:.2f} | {wr:.1%} | {wo:.1%} |")
    # 3. fair walk-forward choice
    yrs = sorted(set(YEARS[LO:]))
    test_years = [y for y in yrs if y >= 2020]

    def walk(Rx, restrict=None):
        stake = paid = 0.0
        chosen = []
        for y in test_years:
            tr = (YEARS < y) & (np.arange(d) >= LO)
            te = YEARS == y
            best, bv = None, -1
            for p, wi, j in itertools.product(range(len(PATS)), range(len(WS)), range(len(PLANS))):
                if restrict is not None and j != restrict:
                    continue
                x = Rx[p, wi, j, tr]
                v = np.nansum(x) / (cost[j] * np.sum(~np.isnan(x)))
                if v > bv:
                    best, bv = (p, wi, j), v
            p, wi, j = best
            x = Rx[p, wi, j, te]
            paid += np.nansum(x)
            stake += cost[j] * np.sum(~np.isnan(x))
            chosen.append(f"{y}: {PATS[p]} ±{WS[wi]} {names[j]} → {np.nansum(x) / (cost[j] * np.sum(~np.isnan(x))):.2f}")
        return paid / stake, chosen

    rr, ch = walk(R[0])
    oth = [walk(R[o])[0] for o in OFFSETS[1:]]
    md += ["", "## Fair choice: best configuration on earlier years, played the next year (2020-2026)", "",
           f"Real date: return **{rr:.2f}** per RM1; other dates: median {np.median(oth):.2f}, range {min(oth):.2f}-{max(oth):.2f} "
           f"({sum(o >= rr for o in oth)} of {len(oth)} at or above the real date).", "", "Choices: " + "; ".join(ch), "",
           "| Plan (tickets) | Fair return, real date | Other dates (median, range) | At or above real |", "|---|---|---|---|"]
    per_plan = {}
    for j, nm in enumerate(names):
        r0, c0 = walk(R[0], j)
        oo = [walk(R[o], j)[0] for o in OFFSETS[1:]]
        per_plan[nm] = (r0, c0)
        md.append(f"| {nm} ({len(PLANS[nm])}) | {r0:.2f} | {np.median(oo):.2f} ({min(oo):.2f}-{max(oo):.2f}) | {sum(o >= r0 for o in oo)} of {len(oo)} |")
    md += ["", "Choices per plan: " + " | ".join(f"{nm}: " + "; ".join(c) for nm, (r0, c) in per_plan.items())]
    # 4. per year for a few configurations
    md += ["", "## Per year (return per RM1), real date", "", "| Pattern ±days plan | " + " | ".join(str(y) for y in yrs) + " |", "|---|" + "---|" * len(yrs)]
    for pat, W, pl in [("hot", 7, "swap10"), ("pos", 7, "swap10"), ("hot/cold100", 7, "swap10"), ("hot", 7, "5+2"),
                       ("pos", 5, "swap10"), ("cold", 7, "swap10")] + [(r[0], r[1], r[2]) for r in rows[:3]]:
        p, wi, j = PATS.index(pat), WS.index(W), names.index(pl)
        x = R[0][p, wi, j]
        md.append(f"| {pat} ±{W} {pl} | " + " | ".join(f"{np.nansum(x[YEARS == y]) / (cost[j] * np.sum(~np.isnan(x[YEARS == y]))):.2f}" for y in yrs) + " |")
    open(os.path.join(A, "LUNAR_OPT.md"), "w").write("\n".join(md) + "\n")
    json.dump({"top": [(a, b, c, r, w) for a, b, c, r, w in rows[:50]], "walk": rr, "walk_other": oth}, open(os.path.join(A, "lunar_opt.json"), "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
