#!/usr/bin/env python3
"""Numbers for an upcoming draw from every watchlist lead, in the order of WATCH_RANK.md (watch_rank.py).

The draw is added to a temporary copy of the data with placeholder numbers: a lead's numbers for a draw use only
earlier draws and that date's astrological values, so the placeholder never enters them. Output: one row per lead and
format with the tickets / systems to play, in analysis/PREDICT_<date>.md and predict_<date>.csv.

python3 analysis/watch_predict.py 2026-10-21
"""

import csv
import datetime as dt
import json
import math
import os
import shutil
import sys
import tempfile

DATE = [a for a in sys.argv[1:] if a[:2] == "20"][0]
sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import watch_score as ws  # noqa: E402

common, ls, xa, tp = ws.common, ws.ls, ws.xa, ws.tp
A = ws.A
LABEL = {"ml8": "Magnum Life", "toto50": "Star Toto", "toto55": "Power Toto", "toto58": "Supreme Toto"}


def with_placeholder():
    tmp = tempfile.mkdtemp(prefix="predict_")
    for f in os.listdir(common.DATA):
        if f.endswith(".csv"):
            shutil.copy(os.path.join(common.DATA, f), tmp)
    day = dt.date.fromisoformat(DATE).strftime("%a").upper()
    for key in LABEL:
        fn = os.path.join(tmp, common.GAMES[key][0])
        rows = list(csv.reader(open(fn)))
        if rows[-1][0] >= DATE:
            continue
        k = len([c for c in rows[0] if c.startswith("n")])
        extra = len(rows[0]) - 2 - k
        rows.append([DATE, day] + [f"{i:02d}" for i in range(1, k + 1)] + [f"{k + i:02d}" for i in range(1, extra + 1)])
        csv.writer(open(fn, "w", newline="")).writerows(rows)
    return tmp


def main():
    common.DATA = with_placeholder()
    ranked = json.load(open(os.path.join(A, "watch_rank.json")))
    order = {(o["game"], o["lead"], o["pat"], o["fmt"]): i + 1 for i, o in enumerate(ranked)}
    names = common.ALL_PARAMS + xa.extra_params()
    out = []
    for key in ws.WATCH:
        ls.init(key)
        W = ls.W
        k = W["k"]
        t = W["g"]["dates"].index(DATE)
        for lead, pat, fmts in ws.WATCH[key]:
            rk = ws.ranking([names.index(x) for x in lead.split(" × ")], pat)
            for f in fmts:
                pats = ls.swap_patterns(k) if f in ("10 tickets", "10 sets") else ws.SYS[f]
                sets = [sorted(int(rk[t, q]) + 1 for q in p) for p in pats]
                price = 1 if key == "ml8" else tp.PRICE[key]
                cost = price * sum(math.comb(len(s), k) for s in sets)
                out.append(dict(rank=order.get((LABEL[key], lead, pat, f), 999), game=LABEL[key], lead=lead, pat=pat,
                                fmt=f, cost=cost, top=" ".join(f"{int(rk[t, q]) + 1:02d}" for q in range(12)),
                                sets=" | ".join(" ".join(f"{x:02d}" for x in s) for s in sets)))
    shutil.rmtree(common.DATA)
    out.sort(key=lambda o: o["rank"])
    with open(os.path.join(A, f"predict_{DATE}.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, list(out[0]))
        w.writeheader()
        w.writerows(out)
    md = [f"# Watchlist numbers for {DATE}", "",
          f"Generated by `analysis/watch_predict.py` before the draw, from the draws up to the day before and the "
          f"astrological values of {DATE}; rank = WATCH_RANK.md (1 = strongest record). *Top 12* = the lead's 12 "
          "highest-ranked numbers, best first.", "",
          "| Rank | Game | Lead | Pattern | Format | Stake (RM) | Top 12 | Tickets / systems |", "|---|---|---|---|---|---|---|---|"]
    md += [f"| {o['rank']} | {o['game']} | {o['lead']} | {o['pat']} | {o['fmt']} | {o['cost']} | {o['top']} | {o['sets']} |" for o in out]
    with open(os.path.join(A, f"PREDICT_{DATE}.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    for o in out:
        print(o["rank"], o["game"], o["lead"], o["pat"], o["fmt"], o["cost"], "|", o["sets"][:120])


if __name__ == "__main__":
    main()
