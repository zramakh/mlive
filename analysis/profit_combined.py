#!/usr/bin/env python3
"""Magnum Life: one ranking of every lead in every format (10 ordinary tickets, System 10 x 1, System 9 x 2
overlap / disjoint) by stake, profit and winning draws on the last 10 draws.

Score = average of two ranks over all lead x format rows: profit margin (profit / stake, so the stake is part
of it) and winning draws (draws that paid any prize). Lower is better. Also: each lead's best format, and the
same score computed on the earlier draws (choice made before the last 10) played on the last 10, against the
shifted calendars.

Needs analysis/profit_arrays/ from profit_rank.py (all four formats).
python3 analysis/profit_combined.py  -> analysis/profit_combined_results.json, analysis/PROFIT_COMBINED.md
"""

import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARR = os.path.join(ROOT, "analysis", "profit_arrays")
FORMATS = [("10_bonus", "10 tickets", 10), ("sys10_bonus", "System 10 × 1", 45),
           ("sys9_overlap_bonus", "System 9 × 2 overlap", 18), ("sys9_disjoint_bonus", "System 9 × 2 disjoint", 18)]
SHIFTS = 2
TOPN = 30
OUT = os.path.join(ROOT, "analysis", "profit_combined_results.json")
MD = os.path.join(ROOT, "analysis", "PROFIT_COMBINED.md")


def rank_desc(x):
    """Rank 1 = largest; ties share the best rank."""
    order = np.argsort(-x, kind="stable")
    xs = x[order]
    r = np.empty(len(x))
    first = np.r_[0, np.flatnonzero(np.diff(xs)) + 1]
    sizes = np.diff(np.r_[first, len(x)])
    r[order] = np.repeat(first + 1, sizes)
    return r


def load(sh):
    rows = {"lead": [], "fmt": [], "stake": [], "profit": [], "wins": [], "per_draw": [], "pre_margin": [],
            "pre_rate": []}
    for tag, name, cost in FORMATS:
        z = np.load(os.path.join(ARR, f"{tag}_sh{sh}.npz"))
        hold = z["hold"].astype(np.float64)
        rows["lead"] += list(z["labels"])
        rows["fmt"] += [name] * len(hold)
        rows["stake"] += [10 * cost] * len(hold)
        rows["profit"] += list(hold.sum(1))
        rows["wins"] += list((hold + cost > 0.5).sum(1))
        rows["per_draw"] += list(hold)
        n_pre = 1002                                                 # earlier draws (25-100% before the last 10)
        rows["pre_margin"] += list(z["pre"] / (n_pre * cost))
        rows["pre_rate"] += list(z["rate_pre"])
    return {k: np.array(v) for k, v in rows.items()}


def score(margin, wins):
    return (rank_desc(margin) + rank_desc(wins)) / 2


def main():
    res = {}
    md = ["# Magnum Life: all formats ranked by stake, profit and winning draws", "",
          "Generated by `analysis/profit_combined.py` from `profit_rank.py` (official prize table, hot / cold counts "
          "updated before every draw). Every lead (26,224) in every format (10 ordinary tickets RM10 a draw, System 10 × 1 "
          "RM45, System 9 × 2 RM18) is one row. *Margin* = profit ÷ stake over the last 10 draws; *winning draws* = draws "
          "that paid any prize. *Score* = average of the row's rank by margin and its rank by winning draws among all "
          "rows (lower is better). Random entries: margin −45% and about 0.7 winning draws in 10, in every format.", ""]
    for sh in range(SHIFTS + 1):
        D = load(sh)
        margin = D["profit"] / D["stake"]
        sc = score(margin, D["wins"])
        pre_sc = score(D["pre_margin"], D["pre_rate"])
        best = np.argsort(sc, kind="stable")[:TOPN]
        pick = np.argsort(pre_sc, kind="stable")[:10]
        row = lambda i: {"lead": D["lead"][i].split("|")[0], "pattern": D["lead"][i].split("|")[1],  # noqa: E731
                         "format": D["fmt"][i], "stake": int(D["stake"][i]), "profit": round(float(D["profit"][i]), 1),
                         "margin_pct": round(100 * float(margin[i]), 1), "wins": int(D["wins"][i]),
                         "score": float(sc[i]), "per_draw": [round(float(x), 1) for x in D["per_draw"][i]],
                         "earlier_margin_pct": round(100 * float(D["pre_margin"][i]), 1),
                         "earlier_win_rate_pct": round(100 * float(D["pre_rate"][i]), 2)}
        out = {"top": [row(i) for i in best], "picked_on_earlier": [row(i) for i in pick],
               "picked_profit_mean": round(float(D["profit"][pick].mean()), 1),
               "picked_stake_mean": round(float(D["stake"][pick].mean()), 1),
               "picked_wins_mean": round(float(D["wins"][pick].mean()), 2),
               "rows_in_profit": int((D["profit"] > 0).sum()),
               "rows_in_profit_with_3plus_wins": int(((D["profit"] > 0) & (D["wins"] >= 3)).sum()),
               "rows": len(sc)}
        if sh == 0:
            # best format per lead (by margin, then winning draws)
            per = {}
            for i in range(len(sc)):
                k = D["lead"][i]
                if k not in per or (margin[i], D["wins"][i]) > (margin[per[k]], D["wins"][per[k]]):
                    per[k] = i
            fmts = {}
            for k, i in per.items():
                fmts[D["fmt"][i]] = fmts.get(D["fmt"][i], 0) + 1
            out["best_format_counts"] = fmts
        res["real" if sh == 0 else f"shift{sh}"] = out
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    R0 = res["real"]
    shs = [res[f"shift{i}"] for i in range(1, SHIFTS + 1)]
    fmt = lambda x: f"{x:+,.0f}"  # noqa: E731
    md += ["| | Real calendar | Shifted calendars |", "|---|---|---|",
           f"| Lead × format rows | {R0['rows']:,} | |",
           f"| Rows in profit on the last 10 draws | {R0['rows_in_profit']:,} | {', '.join(format(x['rows_in_profit'], ',') for x in shs)} |",
           f"| Rows in profit with 3+ winning draws | {R0['rows_in_profit_with_3plus_wins']:,} | {', '.join(format(x['rows_in_profit_with_3plus_wins'], ',') for x in shs)} |",
           f"| Top 10 by the same score on the earlier draws: average profit on the last 10 | {fmt(R0['picked_profit_mean'])} "
           f"(stake {R0['picked_stake_mean']:.0f}, {R0['picked_wins_mean']} winning draws) | "
           f"{', '.join(fmt(x['picked_profit_mean']) for x in shs)} |", "",
           "Best format per lead (by margin): " + ", ".join(f"{k} {v:,}" for k, v in sorted(R0["best_format_counts"].items(),
                                                                                         key=lambda kv: -kv[1])) + ".", "",
           f"## Top {TOPN} on the last 10 draws (hindsight)", "",
           "| # | Lead | Pattern | Format | Stake (RM) | Profit (RM) | Margin | Winning draws | Score | Per draw (RM) | Earlier margin | Earlier win rate |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(R0["top"], 1):
        md.append(f"| {i} | {r['lead']} | {r['pattern']} | {r['format']} | {r['stake']} | {fmt(r['profit'])} | {r['margin_pct']:+,.0f}% | "
                  f"{r['wins']}/10 | {r['score']:,.0f} | {' '.join(fmt(x) for x in r['per_draw'])} | {r['earlier_margin_pct']:+.0f}% | "
                  f"{r['earlier_win_rate_pct']:.1f}% |")
    md += ["", "## Top 10 by the same score on the earlier draws, played on the last 10", "",
           "| # | Lead | Pattern | Format | Earlier margin | Earlier win rate | Profit, last 10 (RM) | Winning draws | Per draw (RM) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(R0["picked_on_earlier"], 1):
        md.append(f"| {i} | {r['lead']} | {r['pattern']} | {r['format']} | {r['earlier_margin_pct']:+.0f}% | {r['earlier_win_rate_pct']:.1f}% | "
                  f"{fmt(r['profit'])} | {r['wins']}/10 | {' '.join(fmt(x) for x in r['per_draw'])} |")
    with open(MD, "w") as fh:
        fh.write("\n".join(md) + "\n")
    for r in R0["top"][:15]:
        print(f"{r['lead'][:45]:<45} {r['pattern']:<8} {r['format']:<22} {r['profit']:>12,.0f} {r['margin_pct']:>10,.0f}% {r['wins']}/10 score {r['score']:.0f}")
    print({k: v for k, v in R0.items() if k not in ("top", "picked_on_earlier")})
    for x in shs:
        print({k: v for k, v in x.items() if k not in ("top", "picked_on_earlier")})
    print("wrote", OUT, "and", MD)


if __name__ == "__main__":
    main()
