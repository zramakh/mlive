#!/usr/bin/env python3
"""Which astrological parameters give the real calendar its extra high hits?

For every lead, excess = high hits on the real calendar minus the same lead's mean over the 20 shifted calendars
(earlier draws, all formats added): 5+ numbers for Sports Toto (toto_full.py), 6+ numbers for Magnum Life
(lead_high_hits.py). Each parameter's score = average excess of the leads that use it (alone or in a pair, all
four patterns), with a z against the same average on each shifted calendar treated as real.

python3 analysis/param_excess.py  -> analysis/PARAM_EXCESS.md, analysis/param_excess_results.json
"""

import itertools
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import extra_astro as xa  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
ARR = os.path.join(A, "profit_arrays")
TOP = 12


def main():
    names = common.ALL_PARAMS + xa.extra_params()
    sets = [()] + [(i,) for i in range(len(names))] + list(itertools.combinations(range(len(names)), 2))
    member = np.zeros((len(sets) * 4, len(names)), bool)
    for si, s in enumerate(sets):
        for j in s:
            member[si * 4:(si + 1) * 4, j] = True
    cnt = member.sum(0)
    sources = {"Magnum Life (6+)": None}
    for key, lab in (("toto50", "Star Toto 6/50 (5+)"), ("toto55", "Power Toto 6/55 (5+)"), ("toto58", "Supreme Toto 6/58 (5+)")):
        sources[lab] = key
    res, md = {}, ["# Which astrological parameters carry the real calendar's extra high hits", "",
                   "Generated by `analysis/param_excess.py`. *Excess* of a lead = its high hits on the real calendar minus its "
                   "mean on 20 shifted calendars (earlier draws, all four formats added; 6+ numbers for Magnum Life, 5+ for "
                   "Toto). A parameter's score = average excess of the leads using it (alone or paired; 230 leads each). "
                   "*z* = that score against the same score computed with each shifted calendar treated as real. With 114 "
                   "parameters, a few |z| > 2.5 are expected by chance.", ""]
    for lab, key in sources.items():
        if key is None:
            X = np.load(os.path.join(ARR, "lead_high_hits_counts.npy"))[:, :, :, 0, 0].sum(2).astype(float)   # leads x calendars
        else:
            X = np.load(os.path.join(ARR, f"toto_full_{key}.npz"))["ST"][:, :, :, 1].sum(2).astype(float)
        nc = X.shape[1]
        exc = X - X[:, 1:].mean(1, keepdims=True)                     # real excess (column 0)
        tot = X.sum(0)
        score = np.zeros((nc, len(names)))
        for c in range(nc):
            others = [x for x in range(nc) if x != c]
            e = X[:, c] - X[:, others].mean(1)
            score[c] = (member * e[:, None]).sum(0) / cnt
        mu, sd = score[1:].mean(0), score[1:].std(0)
        z = (score[0] - mu) / np.maximum(sd, 1e-9)
        order = np.argsort(-z)
        allz = float((tot[0] - tot[1:].mean()) / tot[1:].std())
        res[lab] = {"total_real": float(tot[0]), "total_shifted_mean": float(tot[1:].mean()), "total_z": allz,
                    "params": {names[j]: {"score": float(score[0, j]), "z": float(z[j])} for j in range(len(names))}}
        md += [f"## {lab}", "",
               f"All leads together: {tot[0]:,.0f} high hits on the real calendar vs {tot[1:].mean():,.0f} on the shifted "
               f"calendars (z {allz:+.2f}). Parameters with |z| > 2.5: {int((np.abs(z) > 2.5).sum())} of {len(names)}.", "",
               "| Most excess | z | Excess per lead | | Least excess | z | Excess per lead |", "|---|---|---|---|---|---|---|"]
        for a, b in zip(order[:TOP], order[::-1][:TOP]):
            md.append(f"| {names[a]} | {z[a]:+.2f} | {score[0, a]:+.3f} | | {names[b]} | {z[b]:+.2f} | {score[0, b]:+.3f} |")
        md.append("")
        print(lab, f"total z {allz:+.2f}", "top:", [(names[j], round(float(z[j]), 2)) for j in order[:8]])
    # parameters strong in several games
    labs = list(res)
    zz = np.array([[res[l]["params"][p]["z"] for p in names] for l in labs])
    both = np.argsort(-zz.min(0))[:10]
    md += ["## Parameters with excess in every game", "", "| Parameter | " + " | ".join(labs) + " |", "|---|" + "---|" * len(labs)]
    for j in both:
        md.append(f"| {names[j]} | " + " | ".join(f"{zz[i, j]:+.2f}" for i in range(len(labs))) + " |")
    md.append("")
    with open(os.path.join(A, "PARAM_EXCESS.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(A, "param_excess_results.json"), "w") as fh:
        json.dump(res, fh, indent=1)
    print("\n".join(md[-14:]))


if __name__ == "__main__":
    main()
