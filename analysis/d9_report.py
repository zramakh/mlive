#!/usr/bin/env python3
"""Does the D9 (navamsa) family play a role? From lead_full.py --family d9 (every window) and the full runs.

Per game and history window:
  - the family's leads together: high hits (7+ Magnum Life, 5+ Toto) over the whole history, real calendar vs the
    20 shifted calendars, against the same for all leads;
  - each D9 parameter (alone or paired): the excess high hits of its leads (real minus own shifted mean) and a z
    against the same excess computed with each shifted calendar treated as real;
  - choices made before the last 10 draws, and the 2026-10-18 draw, family vs all leads.

python3 analysis/d9_report.py  -> analysis/D9_REPORT.md
"""

import json
import os
import statistics as st
import sys

import numpy as np

sys.argv = [sys.argv[0], "--family", "d9", "--shifts", "1"]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lead_full as lf  # noqa: E402
import d9  # noqa: E402

A = os.path.join(lf.common.ROOT, "analysis")
WINS = ["all", "last_round", "last5", "last10", "decay10"]
DATE = "2026-10-18"


def tagged(w, fam):
    return ("" if w == "all" else f"_{w}") + ("_d9" if fam else "")


def main():
    names = lf.common.ALL_PARAMS + lf.xa.extra_params()
    sets = lf.lead_sets(names)
    member = np.zeros((len(sets) * lf.NP, len(d9.FAMILY)), bool)
    for si, s in enumerate(sets):
        for fj, p in enumerate(d9.FAMILY):
            if names.index(p) in s:
                member[si * lf.NP:(si + 1) * lf.NP, fj] = True
    md = ["# Does the D9 (navamsa) family play a role?", "",
          "Generated by `analysis/d9_report.py` from `lead_full.py --family d9 --window ...` (history to 2026-10-17) and the "
          "full runs. The family: " + ", ".join(d9.FAMILY) + f" — {len(sets):,} singles and pairs involving them, × 7 "
          f"patterns = {len(sets) * lf.NP:,} leads per game. *High hits* = 7+ numbers (Magnum Life) / 5+ (Toto) in one "
          "combination, over the whole history (all four formats added). *Rank* = the real calendar among 21 (1 = most); "
          "*z* = (real − shifted mean) / shifted spread.", ""]
    for key in lf.FMTS:
        lab = None
        md_g = []
        rows = []
        for w in WINS:
            p = os.path.join(A, "profit_arrays", f"leads7{tagged(w, True)}_{key}.npz")
            pa = os.path.join(A, "profit_arrays", f"leads7{tagged(w, False)}_{key}.npz")
            if not (os.path.exists(p) and os.path.exists(pa)):
                continue
            ST = np.load(p)["ST"]
            STa = np.load(pa)["ST"]
            hf = ST[:, :, :, 1].sum((0, 2)).astype(float)
            ha = STa[:, :, :, 1].sum((0, 2)).astype(float)
            zf = (hf[0] - hf[1:].mean()) / hf[1:].std()
            za = (ha[0] - ha[1:].mean()) / ha[1:].std()
            rows.append(f"| {w} | {hf[0]:,.0f} vs {hf[1:].mean():,.0f} | {int((hf[1:] > hf[0]).sum()) + 1}/21 | {zf:+.2f} | "
                        f"{int((ha[1:] > ha[0]).sum()) + 1}/21 | {za:+.2f} |")
            # per D9 parameter
            X = ST[:, :, :, 1].sum(2).astype(float)                       # leads x calendars
            nc = X.shape[1]
            score = np.zeros((nc, len(d9.FAMILY)))
            for c in range(nc):
                oth = [x for x in range(nc) if x != c]
                e = X[:, c] - X[:, oth].mean(1)
                score[c] = (member * e[:, None]).sum(0) / np.maximum(member.sum(0), 1)
            z = (score[0] - score[1:].mean(0)) / np.maximum(score[1:].std(0), 1e-9)
            md_g.append((w, z))
        res = json.load(open(os.path.join(A, "leads7_d9_results.json")))[key] if os.path.exists(os.path.join(A, "leads7_d9_results.json")) else None
        lab = res["label"] if res else key
        md += [f"## {lab}", "", "### The family's leads together, real calendar vs 20 shifted calendars", "",
               "| Window | D9 high hits: real vs shifted mean | D9 rank | D9 z | All leads rank | All leads z |", "|---|---|---|---|---|---|"] + rows
        md += ["", "### Each D9 parameter: z of its leads' excess high hits (|z| > 2.5 is noteworthy; 13 parameters × 5 windows give a few by chance)", "",
               "| Parameter | " + " | ".join(w for w, _ in md_g) + " |", "|---|" + "---|" * len(md_g)]
        for fj, p in enumerate(d9.FAMILY):
            md.append(f"| {p} | " + " | ".join(f"{z[fj]:+.2f}" for _, z in md_g) + " |")
        # choices before the last 10 and today, family vs all leads (window all)
        md += ["", "### Chosen before the last 10 draws (window: all), profit on them (RM; shifted median)", "",
               "| Leads | Top 10 by earlier profit, best format | #1 re-ranked each draw | Combined score top 10 |", "|---|---|---|---|"]
        for nm, fam in (("D9 family", True), ("all leads", False)):
            rp = os.path.join(A, f"leads7{tagged('all', fam)}_results.json")
            if not os.path.exists(rp):
                continue
            g = json.load(open(rp))[key]
            best = max(g["formats"], key=lambda f: g["formats"][f]["real"]["frozen10"])
            F = g["formats"][best]
            md.append(f"| {nm} | {F['real']['frozen10']:+,.0f} ({st.median(F['shifted']['frozen10']):+,.0f}) in {best} | "
                      f"{F['real']['rolling']:+,.0f} ({st.median(F['shifted']['rolling']):+,.0f}) | "
                      f"{g['combined']['picked_profit_mean']:+,.0f} ({st.median(g['combined']['control']):+,.0f}) |")
        tp_ = os.path.join(A, f"leads7_d9_today_{DATE}.json")
        ta = os.path.join(A, f"leads7_today_{DATE}.json")
        if os.path.exists(tp_) and os.path.exists(ta):
            T, Ta = json.load(open(tp_)).get(key), json.load(open(ta)).get(key)
            if T and Ta:
                md += ["", f"### {DATE}: share of leads that won a prize / best payout (RM)", "", "| Format | D9 family | All leads |", "|---|---|---|"]
                for f in T["formats"]:
                    a, b = T["formats"][f], Ta["formats"][f]
                    md.append(f"| {f} | {100 * a['won'] / (len(sets) * lf.NP):.1f}% / {a['best']:,.0f} | {100 * b['won'] / 45892:.1f}% / {b['best']:,.0f} |")
        md.append("")
    with open(os.path.join(A, "D9_REPORT.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
