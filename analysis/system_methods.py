#!/usr/bin/env python3
"""Magnum Life System 9 x 2 for the non-parameter methods of ten_tickets.py (hot / cold / hot+cold
look-backs, hot/cold + astrology, analogy, embedding / language models, selected parameters,
baselines), on the last 10 draws.

Every method's ranking of the 36 numbers (choices frozen before the last 10 draws) gives two
9-number sets: disjoint (ranks 1-9 and 10-18) or overlap (ranks 1-9 and ranks 1-6 + 10-12).
Per draw: numbers of the 8 drawn inside the better set (a System 9 entry covers every 8 of its 9).
Chance for the same sets from SIMS simulated fair draws.

python3 analysis/system_methods.py  -> analysis/system_methods_results.json, analysis/SYSTEM9_METHODS.md
"""

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ten_tickets as tt  # noqa: E402

KEY = "ml8"
SYS = 9
SIMS = 50000
OUT = os.path.join(common.ROOT, "analysis", "system_methods_results.json")
MD = os.path.join(common.ROOT, "analysis", "SYSTEM9_METHODS.md")


def sets_from(score, structure):
    o = np.argsort(-score)
    a = o[:SYS]
    b = o[SYS:2 * SYS] if structure == "disjoint" else np.r_[o[:SYS - 3], o[SYS:SYS + 3]]
    return [sorted(int(x) for x in a), sorted(int(x) for x in b)]


def main():
    g = common.load_game(KEY)
    k, n = g["k"], g["n"]
    W = g["hit"][-tt.HOLD:, 1:].astype(bool)
    G = tt.generators(KEY)
    rng = np.random.default_rng(9)
    res = {}
    for structure in ("disjoint", "overlap"):
        rows = []
        for name, S in G.items():
            sets = [sets_from(S[i], structure) for i in range(tt.HOLD)]
            if name == "baseline: random":
                r = np.random.default_rng(6)
                sets = [[sorted(r.choice(n, SYS, replace=False).tolist()) for _ in range(2)] for _ in range(tt.HOLD)]
            m = np.array([[W[i, s].sum() for s in sets[i]] for i in range(tt.HOLD)])
            best = m.max(1)
            sim_best, sim5, sim_max = np.zeros(SIMS), np.zeros(SIMS), np.zeros(SIMS)
            for i in range(tt.HOLD):
                Ws = np.zeros((SIMS, n), bool)
                Ws[np.arange(SIMS)[:, None], np.argsort(rng.random((SIMS, n)), 1)[:, :k]] = True
                ms = np.stack([Ws[:, s].sum(1) for s in sets[i]], 1)
                sim_best += ms.max(1)
                sim5 += (ms >= 5).sum(1)
                sim_max = np.maximum(sim_max, ms.max(1))
            rows.append({"method": name, "best_sum": int(best.sum()), "expected": round(float(sim_best.mean()), 2),
                         "chance": round(float((sim_best >= best.sum()).mean()), 4), "max": int(best.max()),
                         "chance_max": round(float((sim_max >= best.max()).mean()), 4),
                         "sets_5plus": int((m >= 5).sum()), "expected_5plus": round(float(sim5.mean()), 3),
                         "per_draw": m.tolist(), "sets": [[[x + 1 for x in s] for s in ss] for ss in sets]})
        rows.sort(key=lambda r: r["chance"])
        res[structure] = rows
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    md = ["# Magnum Life System 9 × 2: non-parameter methods on the last 10 draws", "",
          "Generated by `analysis/system_methods.py`. *Best per draw* = numbers of the 8 drawn inside the better of the two "
          "9-number sets, summed over the 10 draws. Chances from 50,000 simulated fair draws on the same sets.", ""]
    for structure, rows in res.items():
        md += [f"## {structure.capitalize()} sets", "",
               "| Method | Best per draw, summed (expected) | Chance | Most in one set (chance) | Sets with 5+ (expected) |",
               "|---|---|---|---|---|"]
        for r in rows:
            md.append(f"| {r['method']} | {r['best_sum']} ({r['expected']}) | {100 * r['chance']:.1f}% | {r['max']} "
                      f"({100 * r['chance_max']:.1f}%) | {r['sets_5plus']} ({r['expected_5plus']}) |")
        md.append("")
    with open(MD, "w") as fh:
        fh.write("\n".join(md) + "\n")
    for structure, rows in res.items():
        print(structure)
        for r in rows[:8]:
            print(f"  {r['method'][:60]:<60} {r['best_sum']}/{r['expected']} p {r['chance']:.3f} max {r['max']} 5+ {r['sets_5plus']}/{r['expected_5plus']}")


if __name__ == "__main__":
    main()
