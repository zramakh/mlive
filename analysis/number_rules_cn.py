#!/usr/bin/env python3
"""Tai Yi and Mei Hua numbers played directly as lottery numbers (no fitting: each rule names its numbers by date).

Rule numbers per draw date (chinese_div.py table and the plum_trigrams sum), each folded into 1..n
((x − 1) mod n + 1; 0 means no number):
  Tai Yi    host / guest / set calculation (主算, 客算, 定算), host / guest general (主將, 客將), Tai Yi palace, 局 number
  Mei Hua   upper / lower trigram (Xiantian 1-8), moving line (1-6), hexagram (upper − 1) × 8 + lower, the casting sum
Tests per game: each rule's number drawn (chance k / n), the rule's number and its two neighbours (3 numbers), and
all rule numbers of the date together as one ticket; z against exact chance. Luck check: the same with the rule
numbers rolled against the draws (shifted calendars), for the best z among the rules.

python3 analysis/number_rules_cn.py [--shifts 50]  -> analysis/NUMBER_RULES_CN.md
"""

import csv
import datetime as dt
import math
import os
import sys

import numpy as np

NSH = int(sys.argv[sys.argv.index("--shifts") + 1]) if "--shifts" in sys.argv else 50
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import extra_astro as xa  # noqa: E402
import ephemeris as eph  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
LABEL = {"ml8": "Magnum Life", "toto50": "Star Toto", "toto55": "Power Toto", "toto58": "Supreme Toto"}
DIG = dict(zip("一二三四五六七八九", range(1, 10)))


def cn_num(s):
    """'陽遁三十四局' -> 34."""
    s = s.replace("陽遁", "").replace("陰遁", "").replace("局", "")
    if "十" in s:
        a, _, b = s.partition("十")
        return (DIG.get(a, 1) if a else 1) * 10 + (DIG.get(b, 0) if b else 0)
    return DIG[s]


def rules():
    T = {r.pop("date"): r for r in csv.DictReader(open(os.path.join(common.DATA, "astro_params_chinese_div.csv")))}
    X = xa.load_extra()
    R = {}
    for d, r in T.items():
        up, lo = (int(x) for x in X[d]["plum_trigrams"].split("-"))
        mv = int(r["mh_moving_line"])
        R[d] = {"ty_host_calc": int(r["ty_host_calc"]), "ty_guest_calc": int(r["ty_guest_calc"]),
                "ty_set_calc": int(r["ty_set_calc"]), "ty_host_general": int(r["ty_host_general"]),
                "ty_guest_general": int(r["ty_guest_general"]), "ty_palace": int(r["ty_palace"]), "ty_ju": cn_num(r["ty_ju"]),
                "mh_upper": up, "mh_lower": lo, "mh_moving_line": mv, "mh_hexagram": (up - 1) * 8 + lo}
        R[d]["mh_sum"] = None                                          # filled in main() from the casting sum
    return R


def casting_sums():
    """The plum sum s = year branch + lunar month + lunar day (as in extra_astro / chinese_div)."""
    import almanac
    out = {}
    for d in common.load_params():
        day = dt.date.fromisoformat(d)
        lm, ld, _ = eph.lunar_date(day)
        ch = almanac.chinese(day, eph.sun_longitude(eph.julian_day(dt.datetime.combine(day, dt.time(11)))))
        out[d] = almanac.BRANCHES.index(ch["year_pillar"].split()[1]) + 1 + lm + ld
    return out


def fold(x, n):
    return 0 if x is None or x <= 0 else (x - 1) % n + 1


def main():
    R = rules()
    S = casting_sums()
    for d in R:
        R[d]["mh_sum"] = S[d]
    names = list(next(iter(R.values())))
    md = ["# Tai Yi and Mei Hua numbers played directly", "",
          "Generated by `analysis/number_rules_cn.py`. Each rule names its number(s) from the date alone (folded into "
          "1..n); z against exact chance over the whole history; *shifted* = the best z among the rules when the rule "
          f"numbers are rolled against the draws ({NSH} shifted calendars: median and 95th percentile of the best z).", ""]
    for key, lab in LABEL.items():
        g = common.load_game(key)
        k, n = g["k"], g["n"]
        H = g["hit"][:, 1:]
        dates = g["dates"]
        d = len(dates)
        M = np.array([[fold(R[x][p], n) for p in names] for x in dates])   # draws x rules
        rng = np.random.default_rng(5)
        shifts = [0] + [int(s) for s in rng.choice(np.arange(100, d - 100), NSH, replace=False)]

        def stats(Mx):
            single, triple, ticket = {}, {}, None
            p1 = k / n
            for j, p in enumerate(names):
                x = Mx[:, j]
                ok = x > 0
                h = H[np.arange(d)[ok], x[ok] - 1].sum()
                single[p] = (int(h), (h - ok.sum() * p1) / math.sqrt(ok.sum() * p1 * (1 - p1)))
                nb = np.stack([(x - 2) % n, x - 1, x % n], 1)[ok]
                h3 = H[np.arange(d)[ok][:, None], nb].sum()
                e3, v3 = 3 * k / n, 3 * (k / n) * (1 - k / n) * (n - 3) / (n - 1)
                triple[p] = (int(h3), (h3 - ok.sum() * e3) / math.sqrt(ok.sum() * v3))
            hs, es, vs = 0.0, 0.0, 0.0
            for t in range(d):
                u = sorted({int(x) for x in Mx[t] if x > 0})
                m = len(u)
                hs += H[t, [x - 1 for x in u]].sum()
                es += m * k / n
                vs += m * (k / n) * (1 - k / n) * (n - m) / (n - 1)
            ticket = (hs, es, (hs - es) / math.sqrt(vs))
            return single, triple, ticket

        real = stats(M)
        best_s, best_t = [], []
        for sh in shifts[1:]:
            s, t, _ = stats(np.roll(M, sh, axis=0))
            best_s.append(max(z for _, z in s.values()))
            best_t.append(max(z for _, z in t.values()))
        md += [f"## {lab} ({d:,} draws)", "", "| Rule | Number drawn: hits, z | Number ± 1 (3 numbers): hits, z |", "|---|---|---|"]
        for p in names:
            md.append(f"| {p} | {real[0][p][0]}, {real[0][p][1]:+.1f} | {real[1][p][0]}, {real[1][p][1]:+.1f} |")
        hs, es, zt = real[2]
        md += ["", f"All rule numbers of the date as one ticket: {hs:.0f} hits vs {es:.1f} chance (×{hs / es:.3f}, z {zt:+.1f}).",
               f"Best single-number z {max(z for _, z in real[0].values()):+.1f}; shifted calendars' best: median "
               f"{np.median(best_s):+.1f}, 95% {np.quantile(best_s, 0.95):+.1f}. Best 3-number z {max(z for _, z in real[1].values()):+.1f}; "
               f"shifted median {np.median(best_t):+.1f}, 95% {np.quantile(best_t, 0.95):+.1f}.", ""]
        print(lab, "done", flush=True)
    open(os.path.join(A, "NUMBER_RULES_CN.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
