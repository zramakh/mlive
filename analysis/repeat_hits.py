#!/usr/bin/env python3
"""Repeat high hits of a draw's biggest winners.

For each "Biggest payouts today" lead of LEADS7_TODAY_<date>.md, every draw in the whole history (from draw 100)
on which the same lead and format caught 5+ (Toto) or 7+ (Magnum Life) numbers in one combination, with the
payout; numbers for every draw use earlier draws only.

python3 analysis/repeat_hits.py 2026-10-18 [toto50,toto55,toto58]  -> analysis/REPEAT_HITS_<date>.md
"""

import os
import sys

import numpy as np

DATE = sys.argv[1]
WIN = sys.argv[sys.argv.index("--window") + 1] if "--window" in sys.argv else "all"
if "--window" in sys.argv:
    del sys.argv[sys.argv.index("--window"):sys.argv.index("--window") + 2]
KEYS = sys.argv[2].split(",") if len(sys.argv) > 2 else ["ml8", "toto50", "toto55", "toto58"]
sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import watch_score as ws  # noqa: E402
import winners_history as wh  # noqa: E402

wh.DATE = DATE
wh.WIN = WIN
ws.lfw.WINDOW, ws.lfw.TAG = WIN, ("" if WIN == "all" else f"_{WIN}")

ls, tp, tf, pr, common, xa = ws.ls, ws.tp, ws.tf, ws.pr, ws.common, ws.xa
A = os.path.join(common.ROOT, "analysis")


def main():
    W = wh.winners()
    names = common.ALL_PARAMS + xa.extra_params()
    md = [f"# Repeat high hits of the {DATE} winners (history window: {WIN})", "",
          "Generated by `analysis/repeat_hits.py`. For each of the draw's biggest winners: every draw since draw 100 on which "
          "the same lead and format caught 5+ numbers (Toto) or 7+ (Magnum Life) in one combination. Numbers for each draw "
          "use earlier draws only.", ""]
    for key in KEYS:
        ls.init(key)
        Wd = ls.W
        g, d, n, k = Wd["g"], Wd["d"], Wd["n"], Wd["k"]
        Bn = ws.bonus(key, d, n)
        hi = k - 1
        label = [l_ for l_, v in wh.LABELS.items() if v == key][0]
        md += [f"## {label}", "", "| Lead | Pattern | Format | High hits (draws) | Draws with " + f"{hi}+ (best match, payout) |",
               "|---|---|---|---|---|"]
        cache = {}
        for lead, pat, f, comb, pay in W.get(key, []):
            if (lead, pat) not in cache:
                cache[(lead, pat)] = ws.ranking([names.index(x) for x in lead.split(" × ")] if lead != "all draws (no astrology)" else [],
                                                pat + ("" if WIN == "all" else f"@{WIN}"))
            rk = cache[(lead, pat)]
            if f in ("10 tickets", "10 sets"):
                pats, size = ls.swap_patterns(k), k
            else:
                pats = ws.SYS[f]
                size = len(pats[0])
            T = pr.pay_table(size) if key == "ml8" else (tp.pay_table(key) if size == 6 else tf.sys_table(key, size))
            hits = []
            for t in range(100, d):
                win = set(int(x) for x in g["nums"][t])
                bon = set(int(x) + 1 for x in np.flatnonzero(Bn[t]))
                best, p = (0, 0), 0.0
                for q in pats:
                    s = set(int(rk[t, j]) + 1 for j in q)
                    m, b = len(win & s), len(bon & s)
                    p += T[m, b]
                    best = max(best, (m, b))
                if best[0] >= hi:
                    hits.append(f"{g['dates'][t]} ({best[0]}{'+b' if best[1] else ''}, RM{p:,.0f})")
            md.append(f"| {lead} | {pat}{' (new)' if pat in ('cold+100', 'hot/cold100', 'cold/hot100') else ''} | {f} | {len(hits)} | {'; '.join(hits)} |")
            print(label[:12], lead[:45], pat, f, len(hits), "|", "; ".join(hits)[:200], flush=True)
        md.append("")
    out = os.path.join(A, f"REPEAT_HITS{ws.lfw.TAG.upper()}_{DATE}.md")
    with open(out, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
