#!/usr/bin/env python3
"""Do numbers come back around the same date each year?

For every draw t, the numbers drawn in earlier years within ±W days of the same date are counted:
  solar    same calendar date (day of year)
  lunar    same Chinese lunar month and day (months counted as 30 days)
The ticket is the top k (hot) or bottom k (cold) of those counts (8 Magnum Life, 6 Toto; ties by a fixed random
order). Hits against exact chance. Luck check (the calendar's own rhythms kept): the same rule with the window
centred on the date shifted by +30, +45, ... days (50 offsets), so the real "same date" must beat other dates.

python3 analysis/seasonal.py  -> analysis/SEASONAL.md
"""

import datetime as dt
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ephemeris as eph  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
LABEL = {"ml8": "Magnum Life", "toto50": "Star Toto", "toto55": "Power Toto", "toto58": "Supreme Toto"}
OFFSETS = [30 + 6 * i for i in range(50)]                     # 30 ... 324 days


def run(H, pos, years, k, n, W, offset, period, hot):
    """pos: each draw's position in the yearly cycle (0..period-1)."""
    d = len(pos)
    tie = np.random.default_rng(1).random((d, n)) * 1e-6
    hits = draws = 0
    for t in range(d):
        c = (pos + offset - pos[t] + period / 2) % period - period / 2
        m = (np.abs(c) <= W) & (years < years[t])
        if m.sum() < 3:
            continue
        cnt = H[m].sum(0) + tie[t]
        top = np.argsort(-cnt if hot else cnt)[:k]
        hits += H[t, top].sum()
        draws += 1
    e = k * k / n
    v = k * (k / n) * (1 - k / n) * (n - k) / (n - 1)
    return hits / (draws * e), (hits - draws * e) / math.sqrt(draws * v), draws


def main():
    md = ["# Same-date repeats", "", "Generated by `analysis/seasonal.py`. Ticket = the k numbers drawn most (hot) or least (cold) "
          "within ±W days of the same date in earlier years; ratio and z against exact chance; *other dates* = the same "
          "rule centred 30-324 days away (50 offsets): median and the share of offsets beating the real date.", "",
          "| Game | Date | W | Hot: ratio (z) | other dates: median z, share above | Cold: ratio (z) | other dates: median z, share above |",
          "|---|---|---|---|---|---|---|"]
    for key, lab in LABEL.items():
        g = common.load_game(key)
        k, n = g["k"], g["n"]
        H = g["hit"][:, 1:].astype(float)
        days = [dt.date.fromisoformat(x) for x in g["dates"]]
        years = np.array([x.year for x in days])
        solar = np.array([x.timetuple().tm_yday - 1 for x in days], float)
        lun = []
        for x in days:
            lm, ld, _ = eph.lunar_date(x)
            lun.append((lm - 1) * 30 + ld - 1)
        lunar = np.array(lun, float)
        for name, pos, period in (("solar", solar, 365.25), ("lunar", lunar, 360.0)):
            for W in (3, 7):
                row = [lab, name, str(W)]
                for hot in (True, False):
                    r, z, _ = run(H, pos, years, k, n, W, 0, period, hot)
                    oz = [run(H, pos, years, k, n, W, o, period, hot)[1] for o in OFFSETS]
                    row += [f"×{r:.3f} ({z:+.1f})", f"{np.median(oz):+.1f}, {np.mean(np.array(oz) >= z):.0%}"]
                md.append("| " + " | ".join(row) + " |")
                print(md[-1], flush=True)
    open(os.path.join(A, "SEASONAL.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
