#!/usr/bin/env python3
"""Deeper check of the same-lunar-date (hot) result of seasonal.py: every window width W from 1 to 15 days, the real date
against every offset (3-day steps all round the year), each half of the history and each year.

python3 analysis/seasonal_check.py  -> analysis/SEASONAL_CHECK.md
"""
import datetime as dt
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ephemeris as eph  # noqa: E402
import seasonal as se  # noqa: E402

A = se.A


def per_draw(H, pos, years, k, n, W, offset, period):
    d = len(pos)
    tie = np.random.default_rng(1).random((d, n)) * 1e-6
    h = np.full(d, np.nan)
    for t in range(d):
        c = (pos + offset - pos[t] + period / 2) % period - period / 2
        m = (np.abs(c) <= W) & (years < years[t])
        if m.sum() < 3:
            continue
        top = np.argsort(-(H[m].sum(0) + tie[t]))[:k]
        h[t] = H[t, top].sum()
    return h


def main():
    md = ["# Same lunar date, hot: deeper check", "", "Generated by `analysis/seasonal_check.py`. z against exact chance; *offsets* = "
          "the same rule centred 3, 6, ... days away all round the year (the real date is offset 0): its rank among them.", ""]
    for key, lab in se.LABEL.items():
        g = common.load_game(key)
        k, n = g["k"], g["n"]
        H = g["hit"][:, 1:].astype(float)
        days = [dt.date.fromisoformat(x) for x in g["dates"]]
        years = np.array([x.year for x in days])
        pos = np.array([(eph.lunar_date(x)[0] - 1) * 30 + eph.lunar_date(x)[1] - 1 for x in days], float)
        e = k * k / n
        v = k * (k / n) * (1 - k / n) * (n - k) / (n - 1)
        z = lambda h: (np.nansum(h) - np.sum(~np.isnan(h)) * e) / np.sqrt(np.sum(~np.isnan(h)) * v)  # noqa: E731
        md += [f"## {lab}", "", "| W | Real z | Rank among 120 offsets | First half z | Second half z |", "|---|---|---|---|---|"]
        for W in (1, 3, 5, 7, 10, 15):
            h0 = per_draw(H, pos, years, k, n, W, 0, 360.0)
            offs = [z(per_draw(H, pos, years, k, n, W, o, 360.0)) for o in range(3, 360, 3)]
            ok = np.flatnonzero(~np.isnan(h0))
            half = ok[len(ok) // 2]
            md.append(f"| {W} | {z(h0):+.1f} | {1 + sum(o >= z(h0) for o in offs)} of {len(offs) + 1} | {z(h0[:half]):+.1f} | {z(h0[half:]):+.1f} |")
            print(lab, md[-1], flush=True)
            if W == 7:
                yz = [f"{y} ×{np.nansum(h0[years == y]) / (np.sum(~np.isnan(h0[years == y])) * e):.2f}" for y in sorted(set(years)) if np.sum(~np.isnan(h0[years == y]))]
                per_year = ", ".join(yz)
        md += ["", f"W = 7 per year: {per_year}", ""]
    open(os.path.join(A, "SEASONAL_CHECK.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
