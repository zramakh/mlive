#!/usr/bin/env python3
"""Rank every watchlist lead only on draws its choice did not use (out of sample).

First unseen draw per watchlist section:
  original Magnum Life / Toto lists, divisional charts, Chinese divination   2026-10-18 (chosen on data to 10-17)
  new-pattern leads                       2026-10-18, or 2026-10-21 when picked for an 18 Oct win
  history-window and D9 leads             2026-10-21 (added after the 18 Oct results)
  short list (picked in CONSISTENCY.md)   2022-01-01 Magnum Life / Star, 2017-01-01 Power / Supreme (picked on the
                                          years before)
Measure: drawn numbers in the lead's top ticket (8 Magnum Life, 6 Toto) against exact chance, z = (hits − chance) /
spread; also the profit of its first watched format on the same draws.

python3 analysis/rank_oos.py  -> analysis/RANK_OOS.md
"""

import math
import os
import sys

import numpy as np

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import watch_rank as wr  # noqa: E402

ws, ls, common, xa = wr.ws, wr.ls, wr.common, wr.xa
A = wr.A
FROM = {"History-window leads (last round, last 5 / 10, decayed)": "2026-10-21", "D9 (navamsa) family leads": "2026-10-21"}
SHORT = {"ml8": "2022-01-01", "toto50": "2022-01-01", "toto55": "2017-01-01", "toto58": "2017-01-01"}


def first_unseen(key, sec, why):
    if not sec:                                   # added straight from the 18 Oct winners (mercury_combust × aspects_soft)
        return "2026-10-21"
    if sec.startswith("Short list"):
        return SHORT[key]
    if sec.startswith("New-pattern"):
        return "2026-10-21" if ("2026-10-18" in why or "18 Oct" in why) else "2026-10-18"
    return FROM.get(sec, "2026-10-18")


def main():
    notes = wr.watchlist_notes()
    names = common.ALL_PARAMS + xa.extra_params()
    out = []
    for key in ws.WATCH:
        ls.init(key)
        W = ls.W
        k, n, H = W["k"], W["n"], W["H"]
        dates = W["g"]["dates"]
        e = k * k / n
        v = k * (k / n) * (1 - k / n) * (n - k) / (n - 1)
        for lead, pat, fmts in ws.WATCH[key]:
            sec, why = notes.get((lead, pat)) or notes.get(lead, ("", ""))
            start = first_unseen(key, sec, why)
            t0 = next(i for i, d in enumerate(dates) if d >= start)
            rk = ws.ranking([names.index(x) for x in lead.split(" × ")], pat)
            hits = np.take_along_axis(H[t0:], rk[t0:, :k], 1).sum(1)
            nd = len(hits)
            z = (hits.sum() - nd * e) / math.sqrt(nd * v)
            pay, best, cost = wr.score(key, rk, fmts[0], t0)
            out.append(dict(game=wr.LABEL[key], lead=lead, pat=pat, sec=sec, start=start, draws=nd, hits=int(hits.sum()),
                            chance=nd * e, ratio=hits.sum() / (nd * e), z=z, fmt=fmts[0],
                            profit=float(pay[t0:].sum() - cost * nd), stake=float(cost * nd),
                            best=int(best[t0:].max())))
        print(key, flush=True)
    out.sort(key=lambda o: -o["z"])
    md = ["# Watchlist leads ranked on draws they were not chosen on", "",
          "Generated by `analysis/rank_oos.py`. Each lead scored only from the first draw its choice did not use (see the "
          "script); *hits* = drawn numbers in its top ticket (8 Magnum Life, 6 Toto) against exact chance; *z* = (hits − "
          "chance) / spread, so |z| below 2 is within luck. Profit = its first watched format on the same draws. With 1-2 "
          "unseen draws a lead's z says almost nothing; only the short-list leads have years of unseen draws, and they were "
          "the best of 35 pre-picked leads per game on those years, so their z is the top of 35 (luck alone gives about "
          "+2 for the best of 35).", "",
          "| # | Game | Lead (pattern) | Unseen from | Draws | Hits / chance | Ratio | z | Profit, first format (RM) | Source |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for i, o in enumerate(out, 1):
        md.append(f"| {i} | {o['game']} | {o['lead']} ({o['pat']}) | {o['start']} | {o['draws']} | {o['hits']} / {o['chance']:.1f} | "
                  f"×{o['ratio']:.2f} | {o['z']:+.1f} | {o['profit']:+,.0f} on {o['stake']:,.0f} ({o['fmt']}) | {o['sec']} |")
    open(os.path.join(A, "RANK_OOS.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md[4:]))


if __name__ == "__main__":
    main()
