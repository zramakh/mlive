#!/usr/bin/env python3
"""Same-date repeats with all 7 patterns (hot, cold, pos, hot+100, cold+100, hot/cold100, cold/hot100).

The "cell" of draw t is every earlier-year draw within ±W days of the same date (solar day of year, or Chinese lunar
month and day with months as 30 days); the 7 patterns score the numbers from that cell exactly as for a parameter
lead (lead_full.py), the ticket is the top k (8 Magnum Life, 6 Toto), hits against exact chance. Luck check: the
same with the window centred 6, 12, ... days away (59 other dates): the real date's rank.

python3 analysis/seasonal7.py  -> analysis/SEASONAL7.md
"""

import datetime as dt
import os
import sys

import numpy as np

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ephemeris as eph  # noqa: E402
import lead_search10 as ls  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
LABEL = {"ml8": "Magnum Life", "toto50": "Star Toto", "toto55": "Power Toto", "toto58": "Supreme Toto"}
PATS = ["hot", "cold", "pos", "hot+100", "cold+100", "hot/cold100", "cold/hot100"]


def window_sums(X, yi, day, period, W, off, ny):
    """For every draw t: the sum of X over draws of earlier years with day within ±W of day_t + off (circular)."""
    sh = X.shape[1:]
    G = np.zeros((ny, period) + sh, np.float64)
    np.add.at(G, (yi, day), X)
    CY = np.cumsum(G, 0) - G                                   # strictly earlier years, per year
    CYc = np.concatenate([CY, CY, CY], 1)
    P = np.concatenate([np.zeros((ny, 1) + sh), np.cumsum(CYc, 1)], 1)
    c = (day + off) % period + period
    lo, hi = c - W, c + W + 1
    return P[yi, hi] - P[yi, lo]


def main():
    md = ["# Same-date repeats, all 7 patterns", "", "Generated by `analysis/seasonal7.py`. Cell = earlier-year draws within ±W "
          "days of the same date; ticket = the pattern's top k numbers; z against exact chance; rank = the real date "
          "among 60 (itself and 59 other dates 6 days apart; 1 = best).", ""]
    for key, lab in LABEL.items():
        ls.init(key)
        Wd = ls.W
        k, n, H, d = Wd["k"], Wd["n"], Wd["H"].astype(np.float64), Wd["d"]
        days = [dt.date.fromisoformat(x) for x in Wd["g"]["dates"]]
        years = np.array([x.year for x in days])
        yi = years - years.min()
        ny = yi.max() + 1
        lunar = np.array([(eph.lunar_date(x)[0] - 1) * 30 + eph.lunar_date(x)[1] - 1 for x in days])
        solar = np.array([x.timetuple().tm_yday - 1 for x in days])
        e0, v0 = k * k / n, k * (k / n) * (1 - k / n) * (n - k) / (n - 1)
        md += [f"## {lab}", "", "| Calendar | W | " + " | ".join(PATS) + " |", "|---|---|" + "---|" * len(PATS)]
        for cname, day, period in (("lunar", lunar, 360), ("solar", solar, 366)):
            for W in (3, 5, 7, 10):
                Z = np.zeros((60, len(PATS)))
                for oi, off in enumerate(range(0, 360, 6)):
                    cnt = window_sums(Wd["H"], yi, day, period, W, off, ny)
                    dp = window_sums(np.ones((d, 1)), yi, day, period, W, off, ny)
                    Pw = window_sums(Wd["P"], yi, day, period, W, off, ny)
                    ok = (dp[:, 0] >= 3) & (np.arange(d) >= 100)
                    e = dp * k / n
                    zc = (cnt - e) / np.sqrt(e * (1 - k / n) + 1e-6)
                    S = {"hot": cnt - e, "cold": e - cnt, "pos": ((Pw + ls.SMOOTH * Wd["pglob"]) / (dp[:, :, None] + ls.SMOOTH)).sum(1),
                         "hot+100": zc + Wd["hot100"], "cold+100": -zc - Wd["hot100"], "hot/cold100": zc - Wd["hot100"],
                         "cold/hot100": -zc + Wd["hot100"]}
                    for p, pat in enumerate(PATS):
                        top = np.argpartition(-(S[pat][ok] + Wd["tie"][ok]), k, axis=1)[:, :k]
                        h = np.take_along_axis(H[ok], top, 1).sum()
                        Z[oi, p] = (h - ok.sum() * e0) / np.sqrt(ok.sum() * v0)
                cells = [f"{Z[0, p]:+.1f} ({1 + int((Z[1:, p] >= Z[0, p]).sum())})" for p in range(len(PATS))]
                md.append(f"| {cname} | {W} | " + " | ".join(cells) + " |")
                print(lab, md[-1], flush=True)
        md.append("")
    open(os.path.join(A, "SEASONAL7.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
