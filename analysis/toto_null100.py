#!/usr/bin/env python3
"""Star Toto 6/50: the 5- and 6-number hit count of all leads on the real calendar against 100 shifted calendars
(toto_full.py used 20), to pin down how often chance gives as many.

python3 analysis/toto_null100.py [--game toto50] [--shifts 100]  -> analysis/TOTO_NULL100_<GAME>.md, results json
"""

import itertools
import json
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

GAME = sys.argv[sys.argv.index("--game") + 1] if "--game" in sys.argv else "toto50"
NS = int(sys.argv[sys.argv.index("--shifts") + 1]) if "--shifts" in sys.argv else 100
sys.argv = [sys.argv[0], "--games", GAME]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import toto_full as tf  # noqa: E402

tf.SHIFTS = NS
common, xa, ls = tf.common, tf.xa, tf.ls


def main():
    t0 = time.time()
    names = common.ALL_PARAMS + xa.extra_params()
    sets = [()] + [(i,) for i in range(len(names))] + list(itertools.combinations(range(len(names)), 2))
    tasks = [(GAME, sh, sets[i:i + 100]) for sh in range(NS + 1) for i in range(0, len(sets), 100)]
    g = common.load_game(GAME)
    d = len(g["dates"])
    AG = np.zeros((NS + 1, 4, 2, d), np.int64)
    with Pool(4) as pool:
        for j, r in enumerate(pool.imap_unordered(tf.series, tasks), 1):
            AG[r[1]] += r[7]
            if j % 1000 == 0:
                print(f"{j}/{len(tasks)} {time.time() - t0:.0f}s", flush=True)
    R = d - ls.HOLD
    lo = int(0.25 * R)
    res = {"game": g["label"], "shifts": NS, "formats": {}}
    md = [f"# {g['label']}: 5- and 6-number hits of all leads, real calendar vs {NS} shifted calendars", "",
          "Generated by `analysis/toto_null100.py` (same leads, formats and prizes as toto_full.py). *p* = share of shifted "
          "calendars with at least as many hits as the real one.", "",
          "| Format | Draws | Level | Real | Shifted: mean (max) | Rank | p |", "|---|---|---|---|---|---|---|"]
    for fi, f in enumerate(tf.FMT):
        for sname, (a, b) in {"whole history": (lo, d), "first half": (lo, (lo + R) // 2), "second half": ((lo + R) // 2, R),
                              "last 10 draws": (R, d)}.items():
            for li, lv in enumerate(("5+", "6")):
                v = AG[:, fi, li, a:b].sum(1)
                real, null = int(v[0]), v[1:]
                p = float((null >= real).mean())
                res["formats"][f"{f} | {sname} | {lv}"] = {"real": real, "mean": float(null.mean()), "max": int(null.max()),
                                                          "rank": int((null > real).sum()) + 1, "p": p}
                md.append(f"| {f} | {sname} | {lv} | {real:,} | {null.mean():,.0f} ({null.max():,}) | {int((null > real).sum()) + 1}/{NS + 1} | {p:.2f} |")
    with open(os.path.join(common.ROOT, "analysis", f"TOTO_NULL100_{GAME.upper()}.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(common.ROOT, "analysis", f"toto_null100_{GAME}_results.json"), "w") as fh:
        json.dump(res, fh, indent=1)
    print("\n".join(md), f"\n{time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
