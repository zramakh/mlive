#!/usr/bin/env python3
"""Star Toto lunar-date rule (±7 days, hot): how many tickets give the most consistent wins?

Ticket plans built from the rule's ranking of the numbers (best first):
  top6       1 ticket of the top 6
  c+q        the top c numbers on every ticket, the rest every combination from the next q (C(q, 6−c) tickets)
  wheel m    every 6-number combination of the top m (= System m)
  swap10     the 10 sets used in every other 10-set test
Per plan: tickets, share of draws with any prize, return per RM1, return in the worst / median year, and the years
with any prize in at least a quarter of draws; the same plan with the rule centred on 59 other dates (median) shows
what the plan does without the lunar date. Then the last 10 draws for every plan.

python3 analysis/lunar_tickets.py  -> analysis/LUNAR_TICKETS.md
"""
import csv
import datetime as dt
import itertools
import os
import sys
from multiprocessing import Pool

import numpy as np

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import ephemeris as eph  # noqa: E402
import lead_search10 as ls  # noqa: E402
import toto_profit as tp  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
g = common.load_game("toto50")
k, n = 6, 50
H = g["hit"][:, 1:].astype(float)
D = g["dates"]
days = [dt.date.fromisoformat(x) for x in D]
years = np.array([x.year for x in days])
pos = np.array([(eph.lunar_date(x)[0] - 1) * 30 + eph.lunar_date(x)[1] - 1 for x in days], float)
bon = np.array([int(r["bonus"]) for r in csv.DictReader(open(os.path.join(common.DATA, "star_toto_6_50.csv")))])
T = tp.pay_table("toto50")
tie = np.random.default_rng(1).random((len(D), n)) * 1e-6


def plan(c, q):
    return [list(range(c)) + [c + i for i in comb] for comb in itertools.combinations(range(q), 6 - c)]


PLANS = {"top6": [list(range(6))], "5+2": plan(5, 2), "5+3": plan(5, 3), "4+3": plan(4, 3), "4+4": plan(4, 4),
         "3+4": plan(3, 4), "wheel 7": [list(s) for s in itertools.combinations(range(7), 6)],
         "swap10": ls.swap_patterns(6), "3+5": plan(3, 5), "3+6": plan(3, 6),
         "wheel 8": [list(s) for s in itertools.combinations(range(8), 6)]}


def run(off):
    out = {p: [] for p in PLANS}                              # per draw: (date index, payout, best)
    for t in range(len(D)):
        cc = (pos + off - pos[t] + 180) % 360 - 180
        m = (np.abs(cc) <= 7) & (years < years[t])
        if m.sum() < 3:
            continue
        rk = np.argsort(-(H[m].sum(0) + tie[t]))
        win = set(np.flatnonzero(H[t]).tolist())
        for name, P in PLANS.items():
            pay, best = 0.0, (0, 0)
            for s in P:
                ss = {int(rk[i]) for i in s}
                mm, b = len(ss & win), int(bon[t] - 1 in ss)
                pay += T[mm, b]
                best = max(best, (mm, b))
            out[name].append((t, pay, best, [sorted(int(rk[i]) + 1 for i in s) for s in P] if off == 0 and t >= len(D) - 10 else None))
    return off, out


def summary(rows, nt):
    pay = np.array([r[1] for r in rows])
    yr = years[[r[0] for r in rows]]
    yret = [pay[yr == y].sum() / (nt * (yr == y).sum()) for y in sorted(set(yr))]
    ywin = [(pay[yr == y] > 0).mean() for y in sorted(set(yr))]
    return dict(win=(pay > 0).mean(), ret=pay.sum() / (nt * len(pay)), worst=min(yret), med=float(np.median(yret)),
                good_years=sum(w >= 0.25 for w in ywin), years=len(ywin))


def main():
    with Pool(4) as p:
        R = dict(p.map(run, range(0, 360, 6)))
    md = ["# Star Toto lunar-date rule: how many tickets?", "", "Generated by `analysis/lunar_tickets.py` (see the script). 2018-2026, "
          "1,262 draws; *other dates* = the same plan with the rule centred on 59 other dates (median).", "",
          "| Plan | Tickets (RM/draw) | Draws with a prize | Other dates | Return per RM1 | Other dates | Worst year | Median year | Years with a prize in 25%+ of draws |",
          "|---|---|---|---|---|---|---|---|---|"]
    for name, P in PLANS.items():
        nt = len(P)
        s = summary(R[0][name], nt)
        o = [summary(R[off][name], nt) for off in R if off]
        md.append(f"| {name} | {nt} | {s['win']:.1%} | {np.median([x['win'] for x in o]):.1%} | {s['ret']:.2f} | "
                  f"{np.median([x['ret'] for x in o]):.2f} | {s['worst']:.2f} | {s['med']:.2f} | {s['good_years']} of {s['years']} |")
    md += ["", "## Last 10 draws", "", "| Plan | " + " | ".join(D[-10:]) + " | Paid back / stake |", "|---|" + "---|" * 11]
    for name, P in PLANS.items():
        rows = R[0][name][-10:]
        cells = [f"{b[0]}{'+b' if b[1] else ''} / {p:,.0f}" for _, p, b, _ in rows]
        md.append(f"| {name} | " + " | ".join(cells) + f" | RM{sum(r[1] for r in rows):,.0f} / RM{10 * len(P)} |")
    open(os.path.join(A, "LUNAR_TICKETS.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))
    json_last = {name: [dict(date=D[r[0]], tickets=r[3], payout=r[1]) for r in R[0][name][-10:]] for name in PLANS}
    import json
    json.dump(json_last, open(os.path.join(A, "lunar_tickets_last10.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
