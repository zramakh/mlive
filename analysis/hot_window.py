#!/usr/bin/env python3
"""How many previous draws should a hot-number ticket look at?

Ticket at draw t = the k numbers drawn most often in the previous N draws (ties broken
at random), for N in NS, plus exponentially weighted counts with half-life HL draws.
Walk-forward throughout; matches per ticket vs k*k/n.

Protocol per game (D draws; the last HOLD are the final check):
  select   draws 25%-70%: every N is scored, the best (z) is chosen
  test     draws 70% .. D-HOLD: the chosen N, frozen
  last     the last HOLD draws
  rolling  at every draw from 70%, use the N that scored best over the previous ROLL draws
The same pipeline runs on SIMS simulated fair histories (same draw counts) to show what
optimising the look-back gives by chance.

python3 analysis/hot_window.py  (~3 min) -> analysis/hot_window_results.json, analysis/HOT_WINDOW.md
"""

import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
from fairness import simulate  # noqa: E402

NS = [5, 10, 15, 20, 30, 50, 75, 100, 150, 200, 300, 500, 0]          # 0 = all earlier draws
HL = [5, 10, 20, 50, 100, 200]
HOLD = 10
ROLL = 200
SIMS = 300
OUT = os.path.join(common.ROOT, "analysis", "hot_window_results.json")
MD = os.path.join(common.ROOT, "analysis", "HOT_WINDOW.md")


def labels():
    return [f"N={n}" if n else "N=all" for n in NS] + [f"half-life {h}" for h in HL]


def matches(h, k, rng):
    """draws x variants matrix of numbers matched by each variant's ticket (NaN before it is defined)."""
    d, n = h.shape
    cum = np.vstack([np.zeros((1, n)), np.cumsum(h, 0)])
    noise = rng.random((d, n)) * 1e-6
    out = np.full((d, len(NS) + len(HL)), np.nan)
    for j, N in enumerate(NS):
        start = max(N, 1) if N else 1
        cnt = cum[start:d] - (cum[:d - start] if N else 0) + noise[start:]
        top = np.argpartition(-cnt, k - 1, 1)[:, :k]
        out[start:, j] = h[np.arange(start, d)[:, None], top].sum(1)
    for j, hl in enumerate(HL):
        a = 0.5 ** (1 / hl)
        w = np.zeros(n)
        sc = np.zeros((d, n))
        for t in range(d):
            sc[t] = w
            w = a * w + h[t]
        top = np.argpartition(-(sc[1:] + noise[1:]), k - 1, 1)[:, :k]
        out[1:, len(NS) + j] = h[np.arange(1, d)[:, None], top].sum(1)
    return out


def zscore(m, k, n):
    m = m[~np.isnan(m)]
    e = k * k / n
    v = e * (1 - k / n) * (n - k) / (n - 1)
    return float((m.sum() - len(m) * e) / math.sqrt(len(m) * v)) if len(m) else 0.0


def pipeline(M, k, n):
    d = len(M)
    s0, s1, t1 = int(0.25 * d), int(0.7 * d), d - HOLD
    sel = np.array([zscore(M[s0:s1, j], k, n) for j in range(M.shape[1])])
    best = int(np.argmax(sel))
    test = np.array([zscore(M[s1:t1, j], k, n) for j in range(M.shape[1])])
    last = M[t1:, :].sum(0)
    # rolling re-optimisation
    roll = []
    for t in range(s1, d):
        past = np.nansum(M[t - ROLL:t], 0)
        roll.append(M[t, int(np.argmax(past))])
    roll = np.array(roll)
    return {"select_z": sel, "best": best, "test_z": test, "last_matches": last,
            "rolling_test_z": zscore(roll[: t1 - s1], k, n), "rolling_last": float(roll[t1 - s1:].sum())}


def main():
    rng = np.random.default_rng(99)
    lab = labels()
    res = {"variants": lab, "games": {}}
    md = ["# Optimising the hot-number look-back", "",
          "Generated by `analysis/hot_window.py`. Ticket = the k numbers drawn most often in the previous N draws (or "
          "with exponentially decaying weights). Look-back chosen on draws 25–70% of each game, tested on 70% to the last "
          f"{HOLD} draws and on the last {HOLD}. *Fair* columns: the same pipeline on {SIMS} simulated fair histories.", ""]
    for key in common.GAMES:
        g = common.load_game(key)
        h, k, n = g["hit"][:, 1:].astype(float), g["k"], g["n"]
        e = k * k / n
        real = pipeline(matches(h, k, rng), k, n)
        sims = [pipeline(matches(simulate(len(h), k, n, rng).astype(float), k, rng), k, n) for _ in range(SIMS)]
        sim_best_sel = np.array([s["select_z"][s["best"]] for s in sims])
        sim_test_of_best = np.array([s["test_z"][s["best"]] for s in sims])
        sim_roll = np.array([s["rolling_test_z"] for s in sims])
        corr = float(np.corrcoef(real["select_z"], real["test_z"])[0, 1])
        sim_corr = np.array([np.corrcoef(s["select_z"], s["test_z"])[0, 1] for s in sims])
        b = real["best"]
        game = {"label": g["label"], "curve": {lab[j]: {"select_z": round(float(real["select_z"][j]), 2),
                                                         "test_z": round(float(real["test_z"][j]), 2),
                                                         "last10_matches": int(real["last_matches"][j])}
                                               for j in range(len(lab))},
                "chosen": lab[b], "chosen_select_z": round(float(real["select_z"][b]), 2),
                "chosen_test_z": round(float(real["test_z"][b]), 2), "chosen_last10": int(real["last_matches"][b]),
                "last10_expected": round(HOLD * e, 2),
                "rolling_test_z": round(real["rolling_test_z"], 2), "rolling_last10": real["rolling_last"],
                "fair": {"best_select_z_mean": round(float(sim_best_sel.mean()), 2),
                         "share_best_select_z_ge_real": round(float((sim_best_sel >= real["select_z"][b]).mean()), 3),
                         "test_z_of_chosen_5_50_95": [round(float(np.percentile(sim_test_of_best, q)), 2) for q in (5, 50, 95)],
                         "share_test_z_ge_real": round(float((sim_test_of_best >= real["test_z"][b]).mean()), 3),
                         "rolling_test_z_5_50_95": [round(float(np.percentile(sim_roll, q)), 2) for q in (5, 50, 95)],
                         "select_test_corr_mean": round(float(np.nanmean(sim_corr)), 3)},
                "select_test_corr": round(corr, 3)}
        res["games"][key] = game
        f = game["fair"]
        print(f"{g['label']}: chosen {lab[b]} (select z {game['chosen_select_z']:+.2f}, fair best {f['best_select_z_mean']:+.2f}) "
              f"-> test z {game['chosen_test_z']:+.2f} (fair 5-95% {f['test_z_of_chosen_5_50_95']}), last {HOLD} "
              f"{game['chosen_last10']}/{HOLD * e:.1f}; rolling test z {game['rolling_test_z']:+.2f} (fair {f['rolling_test_z_5_50_95']}); "
              f"select-test corr {corr:+.2f} (fair {f['select_test_corr_mean']:+.2f})")
        md += [f"## {g['label']}", "",
               f"Chosen look-back: **{lab[b]}** (selection z {game['chosen_select_z']:+.2f}; the best of the same menu on fair "
               f"histories averages {f['best_select_z_mean']:+.2f}). Test z **{game['chosen_test_z']:+.2f}** (fair histories "
               f"5–95%: {f['test_z_of_chosen_5_50_95'][0]:+.2f} to {f['test_z_of_chosen_5_50_95'][2]:+.2f}); last {HOLD} draws "
               f"{game['chosen_last10']} vs {HOLD * e:.1f}. Re-optimising every draw over the previous {ROLL}: test z "
               f"{game['rolling_test_z']:+.2f} (fair {f['rolling_test_z_5_50_95'][0]:+.2f} to {f['rolling_test_z_5_50_95'][2]:+.2f}), "
               f"last {HOLD} {game['rolling_last10']:.0f}. Correlation between a look-back's selection and test scores: "
               f"{corr:+.2f} (fair {f['select_test_corr_mean']:+.2f}).", "",
               "| Look-back | Selection z | Test z | Last 10 matches |", "|---|---|---|---|"]
        for j, L in enumerate(lab):
            c = game["curve"][L]
            md.append(f"| {L}{' ←' if j == b else ''} | {c['select_z']:+.2f} | {c['test_z']:+.2f} | {c['last10_matches']} |")
        md.append("")
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    with open(MD, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("wrote", OUT, "and", MD)


if __name__ == "__main__":
    main()
