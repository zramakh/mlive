#!/usr/bin/env python3
"""Per game, which single parameters and pairs performed well?

Uses the walk-forward scores of own_leads.py (analysis/own_leads_z.npz): for
each game separately, each of the 78 Vedic / Chinese parameters and 3,003
pairs, each pattern (hot, cold, pos, gap tickets; pos_hit, gap_hit
predictions) and each period of that game's own history (early 25-50%,
valid 50-70%, test 70-100%).

"Performed well" = consistently: ranked by the weakest of the three period
z-scores, and counted when z > 1 in all three periods. The same counts on
the 8 shifted calendars show how many consistent performers chance produces.

For each game's most consistent ticket lead, its ticket for the next draws is
printed and (with --log DATE ...) appended to forward_log.csv as "per_game_best".

python3 analysis/per_game_leads.py [--log 2026-10-18 2026-10-21]
  -> analysis/per_game_leads_results.json, analysis/PER_GAME_LEADS.md
"""

import csv
import datetime as dt
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import own_leads as ol  # noqa: E402

TOPN = 5
OUT = os.path.join(common.ROOT, "analysis", "per_game_leads_results.json")
MD = os.path.join(common.ROOT, "analysis", "PER_GAME_LEADS.md")
LOG = os.path.join(common.ROOT, "analysis", "forward_log.csv")
FAMILY_LABEL = {"vedic": "Vedic", "chinese": "Chinese", "vedic x vedic": "Vedic × Vedic",
                "chinese x chinese": "Chinese × Chinese", "vedic x chinese": "Vedic × Chinese"}


def label(s):
    return " × ".join(ol.PARAMS[j] for j in s)


def main():
    zf = np.load(os.path.join(common.ROOT, "analysis", "own_leads_z.npz"))
    fams = np.array([ol.family(s) for s in ol.SETS])
    single = np.array([len(s) == 1 for s in ol.SETS])
    res = {}
    md = ["# Which parameters performed well, game by game", "",
          "Generated by `analysis/per_game_leads.py` from the walk-forward scores of `own_leads.py`. Every game "
          "is analysed on its own draws only. z = numbers matched by the pattern's ticket vs a fair ticket "
          "(pos_hit / gap_hit: exact hits vs the same prediction ignoring the parameter), in each period of "
          "that game: early (25-50% of its draws), valid (50-70%), test (70-100%). Ranked by the weakest of "
          "the three. *Chance* columns: the same search on 8 shifted calendars, where no parameter can be "
          "linked to the numbers.", ""]
    for key in common.GAMES:
        z = zf[key]                                         # calendars x sets x metrics x periods
        mins = z.min(3)                                     # weakest period
        allpos = (z > 1).all(3)
        game = {"label": common.GAMES[key][1], "metrics": {}}
        md += [f"## {common.GAMES[key][1]}", "",
               "| Pattern | Sets with z > 1 in all 3 periods (chance) | Best weakest-period z (chance) |",
               "|---|---|---|"]
        for mi, m in enumerate(ol.METRICS):
            cnt = int(allpos[0, :, mi].sum())
            cnt_sh = allpos[1:, :, mi].sum(1)
            best = float(mins[0, :, mi].max())
            best_sh = mins[1:, :, mi].max(1)
            entry = {"consistent_sets": cnt, "chance_mean": round(float(cnt_sh.mean()), 1),
                     "chance_range": [int(cnt_sh.min()), int(cnt_sh.max())],
                     "best_weakest_z": round(best, 2), "chance_best_weakest_z_mean": round(float(best_sh.mean()), 2),
                     "top": {}}
            for kind, mask in (("single", single), ("pair", ~single)):
                rows = np.flatnonzero(mask)
                order = rows[np.argsort(-mins[0, rows, mi])][:TOPN]
                entry["top"][kind] = [{"set": label(ol.SETS[i]), "family": fams[i],
                                       **{p: round(float(z[0, i, mi, j]), 2) for j, p in enumerate(ol.PERIODS)}}
                                      for i in order]
            game["metrics"][m] = entry
            md.append(f"| {m} | {cnt} ({cnt_sh.mean():.1f}, range {cnt_sh.min()}–{cnt_sh.max()}) | "
                      f"{best:+.2f} ({best_sh.mean():+.2f}) |")
        md.append("")
        for m in ol.METRICS:
            md += [f"**{m}**", "", "| | Parameter(s) | Family | Early | Valid | Test |", "|---|---|---|---|---|---|"]
            for kind in ("single", "pair"):
                for r in game["metrics"][m]["top"][kind]:
                    md.append(f"| {kind} | {r['set']} | {FAMILY_LABEL[r['family']]} | {r['early']:+.2f} | "
                              f"{r['valid']:+.2f} | {r['test']:+.2f} |")
            md.append("")
        # most consistent ticket lead of this game
        tick = [ol.METRICS.index(t) for t in ol.TICKETS]
        sub = mins[0][:, tick]
        si, ti = np.unravel_index(int(np.argmax(sub)), sub.shape)
        game["best_ticket_lead"] = {"set": label(ol.SETS[si]), "pattern": ol.TICKETS[ti],
                                    "weakest_z": round(float(sub[si, ti]), 2),
                                    **{p: round(float(z[0, si, tick[ti], j]), 2) for j, p in enumerate(ol.PERIODS)}}
        md += [f"Most consistent ticket lead: **{game['best_ticket_lead']['set']}** ({ol.TICKETS[ti]}), "
               f"z early {game['best_ticket_lead']['early']:+.2f}, valid {game['best_ticket_lead']['valid']:+.2f}, "
               f"test {game['best_ticket_lead']['test']:+.2f}.", ""]
        res[key] = game
        print(game["label"], {m: (e["consistent_sets"], e["chance_mean"], e["best_weakest_z"],
                                  e["chance_best_weakest_z_mean"]) for m, e in game["metrics"].items()})
        print("   best ticket lead:", game["best_ticket_lead"])
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    with open(MD, "w") as fh:
        fh.write("\n".join(md))
    print("wrote", OUT, "and", MD)


def tickets(dates, log):
    res = json.load(open(OUT))
    now = dt.datetime.now(dt.timezone.utc).isoformat(timespec="minutes")
    rows = []
    for date in dates:
        for key in common.GAMES:
            lead = res[key]["best_ticket_lead"]
            s = tuple(ol.PARAMS.index(p) for p in lead["set"].split(" × "))
            ol.setup(key, extra_date=date)
            pr = ol.predictions(ol.cell_of(ol.G["codes"], s), last=len(ol.G["codes"]) - 1)
            nums = sorted(int(x) + 1 for x in pr[lead["pattern"]][0])
            rows.append([date, key, "per_game_best", " ".join(f"{x:02d}" for x in nums), now])
            print(date, common.GAMES[key][1], lead["set"], lead["pattern"], nums)
    if log:
        with open(LOG, "a", newline="") as fh:
            csv.writer(fh).writerows(rows)


if __name__ == "__main__":
    if "--log" in sys.argv:
        tickets(sys.argv[sys.argv.index("--log") + 1:], log=True)
    else:
        main()
