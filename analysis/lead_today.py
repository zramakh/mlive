#!/usr/bin/env python3
"""Score every lead (7 patterns, all four formats) on one new draw, after lead_full.py chose them on the draws
before it. The numbers for the draw use only earlier draws; nothing about the draw is used to pick leads.

For each game: how many leads won, the best payouts, and how the leads singled out by lead_full.py did:
the top 10 by earlier profit, by the combined score and by high hits against their own shifted calendars,
plus the best new-pattern (cold+100, hot/cold100, cold/hot100) leads of each list.

python3 analysis/lead_today.py 2026-10-18  -> analysis/LEADS7_TODAY_<date>.md
"""

import itertools
import json
import os
import sys
from multiprocessing import Pool

import numpy as np

DATE = sys.argv[1]
WIN = sys.argv[sys.argv.index("--window") + 1] if "--window" in sys.argv else "all"
sys.argv = [sys.argv[0], "--shifts", "1", "--window", WIN]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lead_full as lf  # noqa: E402  (full data: the new draw is the last row)

common, xa, ls = lf.common, lf.xa, lf.ls
A = os.path.join(common.ROOT, "analysis")


def tier(c, k):
    return lf.tier(int(c), k)


def main():
    names = common.ALL_PARAMS + xa.extra_params()
    sets = [()] + [(i,) for i in range(len(names))] + list(itertools.combinations(range(len(names)), 2))
    idx = {s: i for i, s in enumerate(sets)}
    NL = len(sets) * lf.NP
    lab = lambda i: (" × ".join(names[j] for j in sets[i // lf.NP]) if sets[i // lf.NP] else "all draws (no astrology)",  # noqa: E731
                     lf.PATS[i % lf.NP])
    prev = json.load(open(os.path.join(A, f"leads7{lf.TAG}_results.json")))
    md = [f"# Every lead on the {DATE} draw (7 patterns, history window: {WIN})", "",
          "Generated by `analysis/lead_today.py`. Leads were chosen by `lead_full.py` on the draws up to the day before; "
          "their numbers for this draw use earlier draws only.", ""]
    out = {}
    for key in lf.FMTS:
        g = common.load_game(key)
        if g["dates"][-1] != DATE:
            continue
        P = np.zeros((NL, 4), np.float32)
        C = np.zeros((NL, 4), np.int8)
        tasks = [(key, 0, sets[i:i + 100]) for i in range(0, len(sets), 100)]
        with Pool(4) as pool:
            for _, _, s0, pre, stat, hold, hcode, agg in pool.imap_unordered(lf.series, tasks):
                i0 = idx[s0] * lf.NP
                P[i0:i0 + len(hold)] = hold[:, :, -1]
                C[i0:i0 + len(hold)] = hcode[:, :, -1]
        lf.setup(key)
        fm, cost, k = lf.G["fmt"], lf.G["cost"], lf.G["k"]
        win = sorted(int(x) for x in g["nums"][-1])
        gm = prev[key]
        game = {"label": g["label"], "numbers": win, "formats": {}}
        md += [f"## {g['label']}: {' '.join(f'{x:02d}' for x in win)}", "",
               "| Format (stake) | Leads that won a prize | Best payout | Leads with " + f"{k - 1}+ | New-pattern leads that won |", "|---|---|---|---|---|"]
        for fi, f in enumerate(fm):
            pay = P[:, fi] + cost[f]
            won = pay > 0.5
            newm = np.array([lab(i)[1] in lf.NEW for i in range(NL)])
            game["formats"][f] = {"won": int(won.sum()), "best": float(pay.max()), "hi": int((C[:, fi] >= lf.G["hi"]).sum()),
                                  "new_won": int((won & newm).sum())}
            md.append(f"| {f} (RM{cost[f]}) | {won.sum():,} of {NL:,} ({100 * won.mean():.1f}%) | RM{pay.max():,.0f} | "
                      f"{(C[:, fi] >= lf.G['hi']).sum():,} | {(won & newm).sum():,} |")
        # biggest winners today
        flat = [(float(P[i, fi] + cost[f]), i, fi) for fi, f in enumerate(fm) for i in np.argsort(-P[:, fi])[:15]]
        flat.sort(reverse=True)
        md += ["", "Biggest payouts today:", "", "| Lead | Pattern | Format | Best combination | Payout (RM) |", "|---|---|---|---|---|"]
        seen = 0
        for p, i, fi in flat:
            if seen == 15 or p <= 0:
                break
            ld, pt = lab(i)
            md.append(f"| {ld} | {pt}{' (new)' if pt in lf.NEW else ''} | {fm[fi]} | {tier(C[i, fi], k)} | {p:,.0f} |")
            seen += 1
        # leads singled out by lead_full.py
        pos = {" ".join(lab(i)): i for i in range(NL)}
        lists = {"top by earlier profit": [(r["lead"] + " " + r["pattern"], f) for f, F in gm["formats"].items() for r in F["top_earlier"][:3]],
                 "combined score (chosen on earlier draws)": [(r["lead"], r["format"]) for r in gm["combined"]["picked"]],
                 "high hits against own shifted calendars": [(r["lead"], f) for r in gm["lead_hits"]["top"] for f in fm]}
        md += ["", "Leads singled out on the draws before (lead_full.py), on today's draw:", "",
               "| List | Lead | Format | Best combination | Profit today (RM) |", "|---|---|---|---|---|"]
        for ln, items in lists.items():
            for ld, f in items:
                i = pos.get(ld)
                if i is None:
                    continue
                fi = fm.index(f)
                md.append(f"| {ln} | {ld}{' (new)' if ld.split()[-1] in lf.NEW else ''} | {f} | {tier(C[i, fi], k)} | {P[i, fi]:+,.0f} |")
        md.append("")
        out[key] = game
        print(g["label"], {f: v for f, v in game["formats"].items()})
    with open(os.path.join(A, f"LEADS7{lf.TAG.upper()}_TODAY_{DATE}.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(A, f"leads7{lf.TAG}_today_{DATE}.json"), "w") as fh:
        json.dump(out, fh, indent=1)
    print("wrote", f"LEADS7{lf.TAG.upper()}_TODAY_{DATE}.md")


if __name__ == "__main__":
    main()
