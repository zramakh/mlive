#!/usr/bin/env python3
"""Compare the history windows of lead_full.py: all earlier draws of a cell (all), the most recent unbroken run
(last_round), the 5 / 10 most recent draws (last5, last10), all draws with weight halving every 10 occurrences
(decay10). For every game and format: choices made before the last 10 draws (top 10 by earlier profit, #1 re-ranked
before every draw, combined score, per-lead high hits), the real calendar's rank for high hits over the whole
history, each pattern's z, and the 2026-10-18 forward draw (lead_today.py).

python3 analysis/windows_compare.py [2026-10-18]  -> analysis/WINDOWS_COMPARE.md
"""

import json
import os
import statistics as st
import sys

A = os.path.dirname(os.path.abspath(__file__))
FAM = sys.argv[sys.argv.index("--family") + 1] if "--family" in sys.argv else None
args = [a for a in sys.argv[1:] if a[:2] == "20"]
DATE = args[0] if args else "2026-10-18"
WINS = ["all", "last_round", "last5", "last10", "decay10"]
DESC = {"all": "all earlier draws of the cell", "last_round": "most recent unbroken run of draws in the cell",
        "last5": "5 most recent draws in the cell", "last10": "10 most recent draws in the cell",
        "decay10": "all, weight halving every 10 occurrences"}


def load(w, fam=FAM):
    tag = ("" if w == "all" else f"_{w}") + (f"_{fam}" if fam else "")
    p = os.path.join(A, f"leads7{tag}_results.json")
    t = os.path.join(A, f"leads7{tag}_today_{DATE}.json")
    return (json.load(open(p)) if os.path.exists(p) else None), (json.load(open(t)) if os.path.exists(t) else None)


def main():
    R = {w: load(w) for w in WINS}
    if FAM:                                       # the same windows over all leads, for comparison
        for w in WINS:
            R[f"{w} (all leads)"] = load(w, None)
    wins = [w for w in R if R[w][0]]
    f0 = lambda x: f"{x:+,.0f}"  # noqa: E731
    md = ["# History windows compared", "",
          "Generated by `analysis/windows_compare.py` from `lead_full.py --window ...` (45,892 leads per window, history "
          f"to 2026-10-17, last 10 draws 26 Sep-17 Oct as the test) and `lead_today.py` ({DATE} forward draw). Windows: "
          + "; ".join(f"**{w}** = {DESC[w]}" for w in WINS) + ". Shifted = median over 20 shifted calendars."
          + (f" Rows without a suffix = the {FAM} family's leads only; *(all leads)* = every lead." if FAM else ""), ""]
    keys = list(R[wins[0]][0])
    for key in keys:
        lab = R[wins[0]][0][key]["label"]
        fm = list(R[wins[0]][0][key]["formats"])
        md += [f"## {lab}", "", "### Chosen before the last 10 draws, profit on them (RM; shifted calendars in brackets)", "",
               "| Window | " + " | ".join(f"{f}: top 10 by earlier profit / #1 re-ranked each draw" for f in fm) + " | Combined score top 10 | Per-lead high-hit top 10: high hits on the last 10 |",
               "|---|" + "---|" * (len(fm) + 2)]
        for w in wins:
            g = R[w][0][key]
            cells = []
            for f in fm:
                F = g["formats"][f]
                cells.append(f"{f0(F['real']['frozen10'])} ({f0(st.median(F['shifted']['frozen10']))}) / "
                             f"{f0(F['real']['rolling'])} ({f0(st.median(F['shifted']['rolling']))})")
            C, L = g["combined"], g["lead_hits"]
            md.append(f"| {w} | " + " | ".join(cells) + f" | {f0(C['picked_profit_mean'])} ({f0(st.median(C['control']))}) | "
                      f"{L['forward_real']} ({st.median(L['forward_control']):.0f}) |")
        md += ["", "### Real calendar vs 20 shifted calendars over the whole history: rank of 21 for high hits (z per pattern)", "",
               "| Window | " + " | ".join(fm) + " | Patterns: z (hot / cold / pos / hot+100 / cold+100 / hot/cold100 / cold/hot100) |",
               "|---|" + "---|" * (len(fm) + 1)]
        for w in wins:
            g = R[w][0][key]
            hl = [k_ for k_ in g["null"] if k_.endswith("+") and "| whole history |" in k_]
            ranks = []
            for f in fm:
                k_ = [x for x in hl if x.startswith(f + " |")][0]
                ranks.append(f"{g['null'][k_]['rank']}")
            pz = " / ".join(f"{v['z']:+.1f}" for v in g["patterns"].values())
            md.append(f"| {w} | " + " | ".join(ranks) + f" | {pz} |")
        md += ["", f"### {DATE} (forward draw): leads that won a prize / best payout (RM)", "",
               "| Window | " + " | ".join(fm) + " |", "|---|" + "---|" * len(fm)]
        for w in wins:
            T = R[w][1]
            if not T or key not in T:
                continue
            md.append(f"| {w} | " + " | ".join(f"{T[key]['formats'][f]['won']:,} / {T[key]['formats'][f]['best']:,.0f}" for f in fm) + " |")
        md.append("")
    with open(os.path.join(A, f"WINDOWS_COMPARE{('_' + FAM.upper()) if FAM else ''}.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
