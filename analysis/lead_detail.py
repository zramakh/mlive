#!/usr/bin/env python3
"""Magnum Life: one lead in detail. Every draw on which its entry caught 6+ winning numbers in one 8-number
combination, for each format, with the numbers it played; its profit by format (official prize table); the same
lead on the 20 shifted calendars of high_hits_null.py; and how many of the 26,224 leads reach as many 7+ hits.

python3 analysis/lead_detail.py "pof_rashi × aspect_venus_jupiter" cold
    -> analysis/LEAD_DETAIL_<lead>_<pattern>.md
"""

import os
import re
import sys

import numpy as np

LEAD, PAT = sys.argv[1], sys.argv[2]
del sys.argv[1:3]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import high_hits_null as hn  # noqa: E402
import profit_rank as pr  # noqa: E402

ls, common, xa = hn.ls, hn.common, hn.xa
ARR = os.path.join(common.ROOT, "analysis", "profit_arrays")
COST = {"10 tickets": 10, "System 10 × 1": 45, "System 9 × 2 overlap": 18, "System 9 × 2 disjoint": 18}
SETSZ = {"10 tickets": 8, "System 10 × 1": 10, "System 9 × 2 overlap": 9, "System 9 × 2 disjoint": 9}


def pay_tables():
    out = {}
    for f, s in SETSZ.items():
        out[f] = pr.pay_table(s)
    return out


def run(sh, cols, pat):
    """Per draw: the entry's ranked numbers and, per format, best winning count and payout."""
    hn.setup()
    codes = np.roll(ls.W["codes"], hn.G["shifts"][sh], axis=0)
    k, n, H, Bn = ls.W["k"], ls.W["n"], ls.W["H"], ls.W["Bn"]
    d = len(H)
    cid = np.zeros(d, np.int64)
    for j in cols:
        cid = cid * 1000 + codes[:, j]
    order = np.argsort(cid, kind="stable")
    cs = cid[order]
    first = np.r_[0, np.flatnonzero(np.diff(cs)) + 1]
    starts = np.repeat(first, np.diff(np.r_[first, d]))

    def ex(X):
        xs = X[order]
        c = np.cumsum(xs, 0) - xs
        c = c - c[starts]
        o = np.empty_like(X)
        o[order] = c
        return o
    dp = ex(np.ones((d, 1), np.float32))
    cnt = ex(H)
    e = dp * k / n
    zc = (cnt - e) / np.sqrt(e * (1 - k / n) + 1e-6)
    S = {"hot": cnt - e, "cold": e - cnt,
         "pos": ((ex(ls.W["P"]) + ls.SMOOTH * ls.W["pglob"]) / (dp[:, :, None] + ls.SMOOTH)).sum(1),
         "hot+100": zc + ls.W["hot100"]}[pat] + ls.W["tie"]
    top = np.argsort(-S, 1)[:, :hn.KT]
    war = np.take_along_axis(H, top, 1).astype(int)
    warb = np.take_along_axis(Bn, top, 1).astype(int)
    T = pay_tables()
    res = {}
    for f, pats in hn.G["fmts"].items():
        best = np.zeros(d, int)
        pay = np.zeros(d)
        for q in pats:
            m, b = war[:, q].sum(1), warb[:, q].sum(1)
            best = np.maximum(best, np.minimum(m, 8))
            pay += T[f][m, b]
        res[f] = (best, pay, [[sorted(int(top[t, x]) + 1 for x in q) for q in pats] for t in range(d)])
    return res, dp[:, 0], cid


def main():
    names = common.ALL_PARAMS + xa.extra_params()
    cols = [names.index(x) for x in LEAD.split(" × ")]
    g = common.load_game("ml8")
    d = len(g["dates"])
    R = d - ls.HOLD
    lo = int(0.25 * R)
    real, dp, cid = run(0, cols, PAT)
    md = [f"# Magnum Life lead in detail: {LEAD} ({PAT})", "",
          "Generated by `analysis/lead_detail.py`. Tickets built before each draw from earlier draws in the same cell only "
          f"(cell = the draw's {' and '.join(LEAD.split(' × '))}). Earlier draws = {g['dates'][lo]} to {g['dates'][R - 1]} "
          f"({R - lo} draws); last 10 = {g['dates'][R]} to {g['dates'][-1]}.", ""]
    # summary per format
    md += ["## Hits and profit by format", "",
           "| Format | 6+ hits earlier | 7+ hits earlier | 8 earlier | Profit earlier (RM) | Return earlier | 6+ / 7+ last 10 | Profit last 10 (RM) |",
           "|---|---|---|---|---|---|---|---|"]
    for f, (best, pay, _) in real.items():
        c = COST[f]
        pe = pay[lo:R].sum() - c * (R - lo)
        md.append(f"| {f} | {(best[lo:R] >= 6).sum()} | {(best[lo:R] >= 7).sum()} | {(best[lo:R] >= 8).sum()} | {pe:+,.0f} | "
                  f"{100 * pay[lo:R].sum() / (c * (R - lo)):.0f}% | {(best[R:] >= 6).sum()} / {(best[R:] >= 7).sum()} | "
                  f"{pay[R:].sum() - 10 * c:+,.0f} |")
    md += ["", "Random entries return about 55% of the stake in every format.", ""]
    # every draw with 7+ in any format
    hi = sorted({t for f, (best, _, _) in real.items() for t in range(lo, d) if best[t] >= 7})
    md += ["## Every draw with 7 or more numbers in one combination (any format)", "",
           "| Draw | Cell draws before it | Winning numbers (+ bonus) | Best in format: 10 tickets / Sys 10 / Sys 9 overlap / Sys 9 disjoint | Payout (RM) per format | System 10 numbers played |",
           "|---|---|---|---|---|---|"]
    B = np.argwhere(ls.W["Bn"] > 0)
    for t in hi:
        wn = sorted(int(x) for x in g["nums"][t])
        bn = sorted(int(c) + 1 for r_, c in B if r_ == t)
        bests = " / ".join(str(int(real[f][0][t])) for f in real)
        pays = " / ".join(f"{real[f][1][t]:,.0f}" for f in real)
        md.append(f"| {g['dates'][t]} | {int(dp[t])} | {' '.join(map(str, wn))} (+{' '.join(map(str, bn))}) | {bests} | {pays} | "
                  f"{' '.join(map(str, real['System 10 × 1'][2][t][0]))} |")
    # cells: are the hits in the same cell?
    cells = {}
    for t in hi:
        cells.setdefault(int(cid[t]), []).append(g["dates"][t])
    md += ["", "Cells of those draws (same cell = same " + " and ".join(LEAD.split(" × ")) + "): " +
           "; ".join(f"{len(v)} draw(s): {', '.join(v)}" for v in cells.values()), ""]
    # shifted calendars
    sh7 = []
    for sh in range(1, hn.SHIFTS + 1):
        r_, _, _ = run(sh, cols, PAT)
        sh7.append([int((r_[f][0][lo:R] >= 7).sum()) for f in r_])
    real7 = [int((real[f][0][lo:R] >= 7).sum()) for f in real]
    sh7 = np.array(sh7)
    md += ["## The same lead on 20 shifted calendars (7+ hits on the earlier draws)", "",
           "| Format | Real | Shifted: mean (max) | Shifted calendars with ≥ real |", "|---|---|---|---|"]
    for i, f in enumerate(real):
        md.append(f"| {f} | {real7[i]} | {sh7[:, i].mean():.1f} ({sh7[:, i].max()}) | {(sh7[:, i] >= real7[i]).sum()}/20 |")
    # multiple testing over all leads
    p = os.path.join(ARR, "lead_high_hits_counts.npy")
    if os.path.exists(p):
        A = np.load(p)
        s7 = A[:, :, :, 1, 0].sum(2)                     # leads x calendars, 7+ earlier, all formats
        me = int(sum(real7))
        md += ["", "## How unusual among all leads", "",
               f"This lead: {me} 7+ hits on the earlier draws (all four formats added). Leads with at least {me}: "
               f"{int((s7[:, 0] >= me).sum())} on the real calendar; on the shifted calendars "
               f"{', '.join(str(int((s7[:, c] >= me).sum())) for c in range(1, s7.shape[1]))}. "
               f"Most 7+ hits by any lead: real {int(s7[:, 0].max())}, shifted {', '.join(str(int(s7[:, c].max())) for c in range(1, s7.shape[1]))}.", ""]
    # current tickets for the next draw use all draws so far: report the latest ranking
    md += ["## Its numbers before the last draw", "",
           f"Ranking used for {g['dates'][-1]} (System 10 = top 10): {' '.join(map(str, real['System 10 × 1'][2][-1][0]))}", ""]
    name = re.sub(r"[^A-Za-z0-9]+", "_", f"{LEAD}_{PAT}").strip("_").upper()
    out = os.path.join(common.ROOT, "analysis", f"LEAD_DETAIL_{name}.md")
    with open(out, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))
    print("wrote", out)


if __name__ == "__main__":
    main()
