#!/usr/bin/env python3
"""Recent repeats and hot streaks: real or chance? (no astrology)

The best recent "leads" were really two simple patterns: Power Toto repeating
numbers from the previous draw, and Supreme Toto drawing its recent hot numbers.
For every game this tests, against SIMS simulated histories of fair draws with
the same number of draws:

  windows       10-draw windows: numbers repeated from the previous draw (repeat) and
                hits of the 'k hottest of the previous 100 draws' ticket (hot100);
                how extreme is the latest window, and how often does history reach it?
  persistence   correlation between consecutive non-overlapping 10-draw windows
                (a real tendency would carry over from one window to the next)
  streak        most times any single number came up in a 10-draw window
                (e.g. 28 five times in Power Toto's last 10)
  dispersion    chi-square of number counts in rolling 100- and 300-draw windows
                (a ball / machine bias makes some numbers too common for chance)
  adaptive      walk-forward strategies that play repeat-last (or hot100) only after a
                10-draw window in which it scored at least 1.5x chance; matches on
                the draws actually played vs chance

python3 analysis/recency.py  (~2 min) -> analysis/recency_results.json, analysis/RECENCY.md
"""

import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
from fairness import simulate  # noqa: E402

SIMS = 500
W = 10
HOT = 100
OUT = os.path.join(common.ROOT, "analysis", "recency_results.json")
MD = os.path.join(common.ROOT, "analysis", "RECENCY.md")


def per_draw(h, k):
    """repeat[t], hot100[t] (NaN where undefined)."""
    d, n = h.shape
    rep = np.full(d, np.nan)
    rep[1:] = (h[1:] * h[:-1]).sum(1)
    cum = np.vstack([np.zeros((1, n)), np.cumsum(h, 0)])
    hot = np.full(d, np.nan)
    tie = np.random.default_rng(1).random(n) * 1e-3
    for t in range(HOT, d):
        cnt = cum[t] - cum[t - HOT] + tie
        hot[t] = h[t, np.argpartition(-cnt, k - 1)[:k]].sum()
    return rep, hot


def windows(x):
    """Sums over rolling W-draw windows (valid part only) and over non-overlapping windows."""
    v = x[~np.isnan(x)]
    roll = np.convolve(v, np.ones(W), "valid")
    blocks = v[: len(v) // W * W].reshape(-1, W).sum(1)
    return v, roll, blocks


def stats(h, k):
    rep, hot = per_draw(h, k)
    out = {}
    for name, x in (("repeat", rep), ("hot100", hot)):
        v, roll, blocks = windows(x)
        e = k * k / h.shape[1]
        play = 0
        got = 0
        for i in range(1, len(blocks)):                      # adaptive: play next window if this one was hot
            if blocks[i - 1] >= 1.5 * W * e:
                play += W
                got += blocks[i]
        out[name] = {"last": float(roll[-1]), "max": float(roll.max()),
                     "share_ge_last": float((roll >= roll[-1]).mean()),
                     "persistence": float(np.corrcoef(blocks[:-1], blocks[1:])[0, 1]),
                     "adaptive_played": play, "adaptive_matches": float(got)}
    cum = np.vstack([np.zeros((1, h.shape[1])), np.cumsum(h, 0)])
    roll_counts = (cum[W:] - cum[:-W]).max(1)                  # most times one number came up per window
    out["streak"] = {"last": int(roll_counts[-1]), "max": int(roll_counts.max()),
                     "share_ge_last": float((roll_counts >= roll_counts[-1]).mean())}
    for L in (100, 300):
        e = L * k / h.shape[1]
        chi = (((cum[L::10] - cum[:-L:10][: len(cum[L::10])]) - e) ** 2 / e).sum(1)
        out[f"dispersion{L}"] = {"last": float(chi[-1]), "mean": float(chi.mean()), "max": float(chi.max())}
    return out


def main():
    rng = np.random.default_rng(2027)
    res, md = {}, ["# Recent repeats and hot streaks: real or chance?", "",
                   "Generated by `analysis/recency.py`. Every figure is compared with 500 simulated histories of fair "
                   "draws (same number of draws). *Sim %* = share of simulated histories at least as extreme.", ""]
    for key in common.GAMES:
        g = common.load_game(key)
        h, k, n = g["hit"][:, 1:].astype(float), g["k"], g["n"]
        real = stats(h, k)
        sims = [stats(simulate(len(h), k, n, rng).astype(float), k) for _ in range(SIMS)]
        e = k * k / n

        def pct(path, val, higher=True):
            arr = np.array([s[path[0]][path[1]] for s in sims])
            return round(float(((arr >= val) if higher else (arr <= val)).mean()) * 100, 1)

        game = {"label": g["label"], "expected_per_draw": round(e, 3), "real": real, "vs_fair_sims": {}}
        rows = []
        for name in ("repeat", "hot100"):
            r = real[name]
            sim_last = np.array([s[name]["last"] for s in sims])
            game["vs_fair_sims"][name] = {
                "last_window_pct": pct((name, "last"), r["last"]),
                "max_window_pct": pct((name, "max"), r["max"]),
                "persistence_pct": pct((name, "persistence"), r["persistence"]),
                "persistence_sim_mean": round(float(np.mean([s[name]["persistence"] for s in sims])), 3),
                "adaptive_lift": round(r["adaptive_matches"] / (r["adaptive_played"] * e), 3) if r["adaptive_played"] else None,
                "adaptive_lift_sim": [round(float(np.percentile([s[name]["adaptive_matches"] / (s[name]["adaptive_played"] * e)
                                                                  for s in sims if s[name]["adaptive_played"]], q)), 3)
                                      for q in (5, 50, 95)],
                "last_window_sim_mean": round(float(sim_last.mean()), 2)}
            v = game["vs_fair_sims"][name]
            z_ad = None
            if r["adaptive_played"]:
                var = r["adaptive_played"] * e * (1 - k / n) * (n - k) / (n - 1)
                z_ad = round((r["adaptive_matches"] - r["adaptive_played"] * e) / math.sqrt(var), 2)
                v["adaptive_z"] = z_ad
            rows.append((name, r, v, z_ad))
        game["vs_fair_sims"]["streak"] = {"last_pct": pct(("streak", "last"), real["streak"]["last"]),
                                          "max_pct": pct(("streak", "max"), real["streak"]["max"])}
        for L in (100, 300):
            dk = f"dispersion{L}"
            game["vs_fair_sims"][dk] = {"last_pct": pct((dk, "last"), real[dk]["last"]),
                                        "mean_pct": pct((dk, "mean"), real[dk]["mean"]),
                                        "max_pct": pct((dk, "max"), real[dk]["max"])}
        res[key] = game
        vs = game["vs_fair_sims"]
        md += [f"## {g['label']}", "",
               f"A fair ticket matches {e:.2f} numbers per draw ({W * e:.1f} per {W} draws).", "",
               "| Pattern | Last 10 draws | Sim % | Best 10-draw window in history | Sim % | Window-to-window correlation (fair mean) | Sim % | Adaptive strategy: lift (z) | Fair 5–95% |",
               "|---|---|---|---|---|---|---|---|---|"]
        for name, r, v, z_ad in rows:
            label = "Repeat previous draw" if name == "repeat" else f"{k} hottest of last {HOT}"
            md.append(f"| {label} | {r['last']:.0f} | {v['last_window_pct']} | {r['max']:.0f} | {v['max_window_pct']} | "
                      f"{r['persistence']:+.3f} ({v['persistence_sim_mean']:+.3f}) | {v['persistence_pct']} | "
                      f"{v['adaptive_lift']}× ({z_ad:+.2f}) over {r['adaptive_played']} draws | "
                      f"{v['adaptive_lift_sim'][0]}–{v['adaptive_lift_sim'][2]}× |")
        md += ["", f"Single-number streak: most times one number came up in the last {W} draws = "
               f"{real['streak']['last']} (fair histories reach at least this in their last window {vs['streak']['last_pct']}% "
               f"of the time); most ever in any {W}-draw window = {real['streak']['max']} (sim {vs['streak']['max_pct']}%).", "",
               "Uneven number frequencies (chi-square of counts, rolling windows): " +
               "; ".join(f"{L} draws: latest {real[f'dispersion{L}']['last']:.0f} (sim {vs[f'dispersion{L}']['last_pct']}%), "
                         f"average {real[f'dispersion{L}']['mean']:.1f} (sim {vs[f'dispersion{L}']['mean_pct']}%)" for L in (100, 300)) + ".", ""]
        print(g["label"], json.dumps(vs))
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    with open(MD, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("wrote", OUT, "and", MD)


if __name__ == "__main__":
    main()
