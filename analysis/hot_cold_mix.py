#!/usr/bin/env python3
"""Hot and cold numbers in one ticket.

Ticket at draw t = the h hottest numbers of the previous Nh draws + the (k - h)
coldest numbers of the previous Nc draws (or the k - h most overdue numbers),
never repeating a number. Menu: h = 0..k, Nh and Nc in WINDOWS (0 = all
earlier draws), cold side also "overdue". Walk-forward throughout.

Protocol (as hot_window.py): choose the combination on draws 25-70%, test on 70% ..
D-HOLD and on the last HOLD draws; "rolling" re-chooses it at every draw from
the previous ROLL draws. The same on SIMS simulated fair histories.

python3 analysis/hot_cold_mix.py  (~10 min) -> analysis/hot_cold_mix_results.json, analysis/HOT_COLD_MIX.md
"""

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import hot_window as hw  # noqa: E402
from fairness import simulate  # noqa: E402

WINDOWS = [10, 20, 50, 100, 200, 300, 0]
SIMS = 100
OUT = os.path.join(common.ROOT, "analysis", "hot_cold_mix_results.json")
MD = os.path.join(common.ROOT, "analysis", "HOT_COLD_MIX.md")


def wname(w):
    return f"{w}" if w else "all"


def ranks(h, rng):
    """Per look-back: (first valid draw, hot rank, cold rank) with rank 0 = hottest / coldest; plus overdue."""
    d, n = h.shape
    cum = np.vstack([np.zeros((1, n)), np.cumsum(h, 0)])
    noise = rng.random((d, n)) * 1e-6
    out = {}
    for w in WINDOWS:
        start = w if w else 1
        cnt = np.zeros((d, n))
        cnt[start:] = cum[start:d] - (cum[:d - start] if w else 0)
        cnt += noise
        hot = np.argsort(np.argsort(-cnt, 1), 1)
        cold = np.argsort(np.argsort(cnt, 1), 1)
        out[w] = (start, hot, cold)
    last = np.full(n, -1.0)
    gap = np.zeros((d, n))
    for t in range(d):
        gap[t] = t - last
        last[h[t] > 0] = t
    out["overdue"] = (1, None, np.argsort(np.argsort(-(gap + noise), 1), 1))
    return out


def combos(k):
    out = []
    for hh in range(k + 1):
        for wh in (WINDOWS if hh else [None]):
            for wc in ((WINDOWS + ["overdue"]) if hh < k else [None]):
                out.append((hh, wh, wc))
    return out


def label(c, k):
    hh, wh, wc = c
    parts = [f"{hh} hot (last {wname(wh)})"] if hh else []
    if wc is not None:
        parts.append(f"{k - hh} overdue" if wc == "overdue" else f"{k - hh} cold (last {wname(wc)})")
    return " + ".join(parts)


def matrix(h, k, rng):
    """draws x combinations matrix of numbers matched."""
    d, n = h.shape
    R = ranks(h, rng)
    C = combos(k)
    M = np.full((d, len(C)), np.nan)
    hb = h.astype(bool)
    for j, (hh, wh, wc) in enumerate(C):
        start = max(R[wh][0] if hh else 1, R[wc][0] if wc is not None else 1)
        mask = np.zeros((d, n), bool)
        if hh:
            mask = R[wh][1] < hh
        if hh < k:
            cr = R[wc][2].astype(float)
            cr[mask] = np.inf
            pick = np.argpartition(cr, k - hh - 1, 1)[:, :k - hh]
            np.put_along_axis(mask, pick, True, 1)
        m = (hb & mask).sum(1).astype(float)
        m[:start] = np.nan
        M[:, j] = m
    return M, C


def main():
    rng = np.random.default_rng(7)
    res, md = {"games": {}}, ["# Hot and cold numbers in one ticket", "",
                               "Generated by `analysis/hot_cold_mix.py`. Ticket = h hottest numbers of the last Nh draws + "
                               "(k − h) coldest of the last Nc draws (or most overdue). The combination is chosen on draws "
                               f"25–70% of each game and tested on 70% → last {hw.HOLD} and on the last {hw.HOLD}; *fair* = the "
                               f"same pipeline on {SIMS} simulated fair histories.", ""]
    for key in common.GAMES:
        g = common.load_game(key)
        h, k, n = g["hit"][:, 1:].astype(float), g["k"], g["n"]
        e = k * k / n
        M, C = matrix(h, k, rng)
        real = hw.pipeline(M, k, n)
        sims = [hw.pipeline(matrix(simulate(len(h), k, n, rng).astype(float), k, rng)[0], k, n) for _ in range(SIMS)]
        b = real["best"]
        sb = np.array([s["select_z"][s["best"]] for s in sims])
        st = np.array([s["test_z"][s["best"]] for s in sims])
        sr = np.array([s["rolling_test_z"] for s in sims])
        corr = float(np.corrcoef(real["select_z"], real["test_z"])[0, 1])
        sc = np.array([np.corrcoef(s["select_z"], s["test_z"])[0, 1] for s in sims])
        top_sel = np.argsort(-real["select_z"])[:10]
        game = {"label": g["label"], "combinations": len(C), "chosen": label(C[b], k),
                "chosen_select_z": round(float(real["select_z"][b]), 2), "chosen_test_z": round(float(real["test_z"][b]), 2),
                "chosen_last10": int(real["last_matches"][b]), "last10_expected": round(hw.HOLD * e, 2),
                "rolling_test_z": round(real["rolling_test_z"], 2), "rolling_last10": real["rolling_last"],
                "select_test_corr": round(corr, 3),
                "top10_by_selection": [{"ticket": label(C[j], k), "select_z": round(float(real["select_z"][j]), 2),
                                        "test_z": round(float(real["test_z"][j]), 2),
                                        "last10": int(real["last_matches"][j])} for j in top_sel],
                "fair": {"best_select_z_mean": round(float(sb.mean()), 2),
                         "test_z_of_chosen_5_95": [round(float(np.percentile(st, q)), 2) for q in (5, 95)],
                         "share_test_z_ge_real": round(float((st >= real["test_z"][b]).mean()), 3),
                         "rolling_test_z_5_95": [round(float(np.percentile(sr, q)), 2) for q in (5, 95)],
                         "select_test_corr_5_95": [round(float(np.nanpercentile(sc, q)), 3) for q in (5, 95)]}}
        res["games"][key] = game
        f = game["fair"]
        print(f"{g['label']}: chosen {game['chosen']} (select z {game['chosen_select_z']:+.2f}, fair best {f['best_select_z_mean']:+.2f})"
              f" -> test z {game['chosen_test_z']:+.2f} (fair {f['test_z_of_chosen_5_95']}), last 10 {game['chosen_last10']}/{hw.HOLD * e:.1f};"
              f" rolling {game['rolling_test_z']:+.2f} (fair {f['rolling_test_z_5_95']}); corr {corr:+.2f} (fair {f['select_test_corr_5_95']})")
        md += [f"## {g['label']} ({len(C)} combinations)", "",
               f"Chosen: **{game['chosen']}** (selection z {game['chosen_select_z']:+.2f}; the best of the same menu on fair "
               f"histories averages {f['best_select_z_mean']:+.2f}). Test z **{game['chosen_test_z']:+.2f}** (fair 5–95%: "
               f"{f['test_z_of_chosen_5_95'][0]:+.2f} to {f['test_z_of_chosen_5_95'][1]:+.2f}); last {hw.HOLD} draws "
               f"{game['chosen_last10']} vs {hw.HOLD * e:.1f}. Re-chosen every draw: test z {game['rolling_test_z']:+.2f} "
               f"(fair {f['rolling_test_z_5_95'][0]:+.2f} to {f['rolling_test_z_5_95'][1]:+.2f}), last {hw.HOLD} "
               f"{game['rolling_last10']:.0f}. Selection-vs-test correlation over all combinations {corr:+.2f} (fair 5–95%: "
               f"{f['select_test_corr_5_95'][0]:+.2f} to {f['select_test_corr_5_95'][1]:+.2f}).", "",
               "| Top 10 on selection draws | Selection z | Test z | Last 10 |", "|---|---|---|---|"]
        for r in game["top10_by_selection"]:
            md.append(f"| {r['ticket']} | {r['select_z']:+.2f} | {r['test_z']:+.2f} | {r['last10']} |")
        md.append("")
    with open(OUT, "w") as fh:
        json.dump(res, fh, indent=1)
    with open(MD, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("wrote", OUT, "and", MD)


if __name__ == "__main__":
    main()
