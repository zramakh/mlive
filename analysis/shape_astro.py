#!/usr/bin/env python3
"""Does the shape of a draw depend on astrology? Sum of the numbers, odd count, high count (above n / 2) and
consecutive pairs, by parameter value.

For each game, shape measure and parameter (the 114 base parameters plus the muhurta and transit families, alone):
  fit   the spread of the per-value means of the shape (F statistic) over the whole history
  fair  before each year, each value's mean shape on earlier years only predicts that year's draws; the gain over the
        overall earlier mean (reduction in squared error, %) pooled over the years after the first two
Luck check: the same on shifted calendars (parameter values rolled against the draws). If shape followed the sky,
the real calendar would show more large F values and a positive fair gain.

python3 analysis/shape_astro.py [--shifts 10]  -> analysis/SHAPE_ASTRO.md
"""

import csv
import os
import sys

import numpy as np

NSH = int(sys.argv[sys.argv.index("--shifts") + 1]) if "--shifts" in sys.argv else 10
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import extra_astro as xa  # noqa: E402

A = os.path.join(common.ROOT, "analysis")
LABEL = {"ml8": "Magnum Life", "toto50": "Star Toto", "toto55": "Power Toto", "toto58": "Supreme Toto"}
SHAPES = ["sum", "odd", "high", "consecutive"]


def table(path, dates):
    rows = {r.pop("date"): r for r in csv.DictReader(open(path))}
    names = [p for p in next(iter(rows.values())) if len({r[p] for r in rows.values()}) > 1]
    cols = []
    for p in names:
        vals = sorted({r[p] for r in rows.values()})
        ix = {v: i for i, v in enumerate(vals)}
        cols.append([ix[rows[d][p]] for d in dates])
    return names, np.array(cols).T


def fstat(y, c):
    u, inv = np.unique(c, return_inverse=True)
    if len(u) < 2:
        return 0.0
    cnt = np.bincount(inv)
    mean = np.bincount(inv, weights=y) / cnt
    between = (cnt * (mean - y.mean()) ** 2).sum() / (len(u) - 1)
    within = ((y - mean[inv]) ** 2).sum() / (len(y) - len(u))
    return between / max(within, 1e-12)


def fair_gain(y, c, years):
    ys = sorted(set(years))
    se_cell = se_all = 0.0
    for t in ys[2:]:
        tr, te = years < t, years == t
        mu = y[tr].mean()
        u, inv = np.unique(c[tr], return_inverse=True)
        cnt = np.bincount(inv)
        mean = (np.bincount(inv, weights=y[tr]) + 10 * mu) / (cnt + 10)   # shrunk to the overall mean
        look = dict(zip(u, mean))
        pred = np.array([look.get(v, mu) for v in c[te]])
        se_cell += ((y[te] - pred) ** 2).sum()
        se_all += ((y[te] - mu) ** 2).sum()
    return 100 * (1 - se_cell / se_all)


def main():
    md = ["# Draw shape by astrology", "", "Generated by `analysis/shape_astro.py`. *Large F* = parameters whose per-value means of the "
          "shape differ at the 1% level (about 1% expected by chance); *fair gain* = how much predicting each year's shape "
          "from earlier same-value draws beats the plain earlier average (%, mean over parameters; best parameter in "
          "brackets). Shifted calendars: median.", "",
          "| Game | Shape | Params | Large F: real (shifted) | Fair gain, mean: real (shifted) | Best fair gain: real (shifted) |",
          "|---|---|---|---|---|---|"]
    from scipy.stats import f as fdist
    for key, lab in LABEL.items():
        g = common.load_game(key)
        k, n = g["k"], g["n"]
        dates = g["dates"]
        H = g["hit"][:, 1:]
        nums = [np.flatnonzero(r) + 1 for r in H]
        shape = {"sum": np.array([x.sum() for x in nums], float), "odd": np.array([(x % 2).sum() for x in nums], float),
                 "high": np.array([(x > n / 2).sum() for x in nums], float),
                 "consecutive": np.array([(np.diff(x) == 1).sum() for x in nums], float)}
        years = np.array([int(x[:4]) for x in dates])
        extra = xa.codes_all(dates)                                # the 114 base parameters
        n1, c1 = table(os.path.join(common.DATA, "astro_params_muhurta.csv"), dates)
        n2, c2 = table(os.path.join(common.DATA, f"astro_params_transit_{key}.csv"), dates)
        C = np.hstack([extra[:, :114], c1, c2])
        rng = np.random.default_rng(11)
        shifts = [0] + [int(s) for s in rng.choice(np.arange(160, len(dates) - 160), NSH, replace=False)]
        for sname, y in shape.items():
            res = []
            for sh in shifts:
                Cs = np.roll(C, sh, axis=0)
                big = gains = 0
                gl = []
                for j in range(Cs.shape[1]):
                    c = Cs[:, j]
                    F = fstat(y, c)
                    df1 = len(np.unique(c)) - 1
                    big += fdist.sf(F, df1, len(y) - df1 - 1) < 0.01
                    gl.append(fair_gain(y, c, years))
                res.append((big, float(np.mean(gl)), float(np.max(gl))))
            r, s = res[0], res[1:]
            md.append(f"| {lab} | {sname} | {C.shape[1]} | {r[0]} ({np.median([x[0] for x in s]):.0f}) | {r[1]:+.2f}% "
                      f"({np.median([x[1] for x in s]):+.2f}%) | {r[2]:+.2f}% ({np.median([x[2] for x in s]):+.2f}%) |")
            print(md[-1], flush=True)
    open(os.path.join(A, "SHAPE_ASTRO.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
